CREATE OR REPLACE VIEW room_operational_facts AS
SELECT r.id AS room_id,
       EXISTS(SELECT 1 FROM stay_room_segments s WHERE s.room_id=r.id AND s.exited_at IS NULL) AS occupied,
       false AS has_blocking_issue,
       EXISTS(SELECT 1 FROM housekeeping_tasks t WHERE t.room_id=r.id AND t.status IN ('PENDING','IN_PROGRESS')) AS has_open_cleaning_task,
       EXISTS(SELECT 1 FROM stay_room_segments s WHERE s.room_id=r.id) AS has_usage_history
FROM rooms r;
COMMENT ON TABLE housekeeping_task_logs IS 'Append-only business history through service API; no guest data. Version zero records creation, including migrated real checkout creation facts.';
COMMENT ON TABLE housekeeping_tasks IS 'Checkout and manual cleaning workflow. Cleaning state remains exclusively in rooms.cleaning_status.';
