    ADD COLUMN assigned_at TIMESTAMPTZ,
    ADD COLUMN claimed_at TIMESTAMPTZ,
    ADD COLUMN started_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    ADD COLUMN started_at TIMESTAMPTZ,
    ADD COLUMN completed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    ADD COLUMN completed_at TIMESTAMPTZ,
    ADD COLUMN completion_notes VARCHAR(1000) NOT NULL DEFAULT '',
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    ADD CONSTRAINT ck_task_source CHECK (
        (source='CHECKOUT' AND task_type='CHECKOUT_CLEANING' AND source_id IS NOT NULL
         AND stay_record_id IS NOT NULL AND room_segment_id IS NOT NULL AND source_id=stay_record_id)
        OR (source='MANUAL' AND task_type='MANUAL_CLEANING' AND source_id IS NULL
         AND stay_record_id IS NULL AND room_segment_id IS NULL AND length(trim(notes))>0)),
    ADD CONSTRAINT ck_task_assignment CHECK (
        (assigned_to IS NULL AND assigned_by IS NULL AND assigned_at IS NULL AND claimed_at IS NULL)
        OR (assigned_to IS NOT NULL AND assigned_by IS NOT NULL AND assigned_at IS NOT NULL
            AND assigned_at>=created_at AND (claimed_at IS NULL OR claimed_at=assigned_at))),
    ADD CONSTRAINT ck_task_workflow CHECK (
        (status='PENDING' AND started_by IS NULL AND started_at IS NULL AND completed_by IS NULL AND completed_at IS NULL)
        OR (status='IN_PROGRESS' AND assigned_to IS NOT NULL AND started_by IS NOT NULL
            AND started_at IS NOT NULL AND started_at>=created_at AND completed_by IS NULL AND completed_at IS NULL)
        OR (status='COMPLETED' AND assigned_to IS NOT NULL AND started_by IS NOT NULL
            AND started_at IS NOT NULL AND started_at>=created_at AND completed_by=assigned_to
            AND completed_by IS NOT NULL AND completed_at IS NOT NULL AND completed_at>=started_at));

DROP INDEX uq_room_open_cleaning_task;
CREATE UNIQUE INDEX uq_room_open_cleaning_task ON housekeeping_tasks(room_id)
    WHERE status IN ('PENDING','IN_PROGRESS');
CREATE INDEX ix_tasks_assignee_state ON housekeeping_tasks(assigned_to,status,created_at DESC,id DESC);

CREATE TABLE housekeeping_task_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES housekeeping_tasks(id) ON DELETE RESTRICT,
    action VARCHAR(30) NOT NULL CHECK (action IN ('AUTO_CREATE','MANUAL_CREATE','CLAIM','ASSIGN','REASSIGN','START','COMPLETE')),
    from_status VARCHAR(20) CHECK (from_status IN ('PENDING','IN_PROGRESS','COMPLETED')),
    to_status VARCHAR(20) NOT NULL CHECK (to_status IN ('PENDING','IN_PROGRESS','COMPLETED')),
    from_assignee BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    to_assignee BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    operator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    operated_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(1000) NOT NULL DEFAULT '',
    task_version BIGINT NOT NULL CHECK (task_version>=0),
    UNIQUE(task_id,task_version)
);
CREATE INDEX ix_task_logs_history ON housekeeping_task_logs(task_id,id);
