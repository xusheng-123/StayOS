-- Incremental only. No existing rooms/accounts or historical migrations are changed.
CREATE TABLE guests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL CHECK (length(trim(display_name)) > 0),
    document_type VARCHAR(20) NOT NULL CHECK (document_type IN ('ID_CARD','PASSPORT','OTHER')),
    document_ciphertext VARCHAR(500) NOT NULL,
    document_mask VARCHAR(100) NOT NULL,
    phone_ciphertext VARCHAR(500),
    phone_mask VARCHAR(100) NOT NULL DEFAULT '',
    encryption_key_id VARCHAR(30) NOT NULL,
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE stay_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_in_at TIMESTAMPTZ NOT NULL,
    expected_check_out_at TIMESTAMPTZ NOT NULL,
    actual_check_out_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_HOUSE' CHECK (status IN ('IN_HOUSE','CHECKED_OUT')),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    checked_out_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (expected_check_out_at > check_in_at),
    CHECK ((status='IN_HOUSE' AND actual_check_out_at IS NULL AND checked_out_by IS NULL)
        OR (status='CHECKED_OUT' AND actual_check_out_at >= check_in_at AND checked_out_by IS NOT NULL))
);
CREATE TABLE stay_guests (
    stay_record_id BIGINT NOT NULL REFERENCES stay_records(id) ON DELETE RESTRICT,
    guest_id BIGINT NOT NULL REFERENCES guests(id) ON DELETE RESTRICT,
    is_primary BOOLEAN NOT NULL DEFAULT false,
    position INTEGER NOT NULL CHECK (position BETWEEN 0 AND 19),
    PRIMARY KEY (stay_record_id,guest_id),
    UNIQUE (stay_record_id,position)
);
CREATE UNIQUE INDEX uq_stay_primary_guest ON stay_guests(stay_record_id) WHERE is_primary;
CREATE TABLE stay_room_segments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_record_id BIGINT NOT NULL REFERENCES stay_records(id) ON DELETE RESTRICT,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    room_number_snapshot VARCHAR(20) NOT NULL,
    room_type_name_snapshot VARCHAR(100) NOT NULL,
    entered_at TIMESTAMPTZ NOT NULL,
    exited_at TIMESTAMPTZ,
    end_reason VARCHAR(20),
    CHECK ((exited_at IS NULL AND end_reason IS NULL)
       OR (exited_at >= entered_at AND end_reason IN ('CHECK_OUT','ROOM_CHANGE')))
);
CREATE UNIQUE INDEX uq_room_active_segment ON stay_room_segments(room_id) WHERE exited_at IS NULL;
CREATE UNIQUE INDEX uq_stay_active_segment ON stay_room_segments(stay_record_id) WHERE exited_at IS NULL;
CREATE INDEX ix_segments_stay_history ON stay_room_segments(stay_record_id,id);
CREATE INDEX ix_segments_room_history ON stay_room_segments(room_id);
CREATE INDEX ix_stays_status_time ON stay_records(status,check_in_at DESC,id DESC);
CREATE INDEX ix_stay_guests_guest ON stay_guests(guest_id);
CREATE TABLE idempotency_requests (
    operator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    operation VARCHAR(40) NOT NULL CHECK (operation='CHECK_IN'),
    request_key UUID NOT NULL,
    request_hash VARCHAR(64) NOT NULL CHECK (request_hash ~ '^[a-f0-9]{64}$'),
    result_stay_id BIGINT REFERENCES stay_records(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '24 hours'),
    PRIMARY KEY (operator_id,operation,request_key),
    CHECK (expires_at > created_at)
);
COMMENT ON TABLE guests IS 'Per-registration guest snapshot. Sensitive fields AES-256-GCM encrypted; no global guest matching or full-document read API.';
COMMENT ON TABLE idempotency_requests IS 'Committed success only; entire transaction rolls back on failure. Expired keys are retained and rejected, never recycled automatically.';
CREATE OR REPLACE VIEW room_operational_facts AS
SELECT r.id AS room_id,
       EXISTS(SELECT 1 FROM stay_room_segments s WHERE s.room_id=r.id AND s.exited_at IS NULL) AS occupied,
       false AS has_blocking_issue, false AS has_open_cleaning_task,
       EXISTS(SELECT 1 FROM stay_room_segments s WHERE s.room_id=r.id) AS has_usage_history
FROM rooms r;
COMMENT ON VIEW room_operational_facts IS
'Stage 3: occupancy/history derive from stay_room_segments. Issues/tasks remain absent until their own incremental migrations.';
