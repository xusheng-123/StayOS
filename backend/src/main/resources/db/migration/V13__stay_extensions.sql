-- V1.1: change the departure plan without changing occupancy or creating cleaning work.
ALTER TABLE stay_records ADD COLUMN version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0);

CREATE TABLE stay_extensions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_record_id BIGINT NOT NULL REFERENCES stay_records(id) ON DELETE RESTRICT,
    segment_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    old_expected_check_out_at TIMESTAMPTZ NOT NULL,
    new_expected_check_out_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(1000) NOT NULL CHECK (length(trim(reason)) BETWEEN 1 AND 1000),
    operator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    operated_at TIMESTAMPTZ NOT NULL,
    stay_version BIGINT NOT NULL CHECK (stay_version > 0),
    UNIQUE (stay_record_id, stay_version),
    FOREIGN KEY (segment_id, stay_record_id, room_id)
        REFERENCES stay_room_segments(id, stay_record_id, room_id) ON DELETE RESTRICT,
    CHECK (old_expected_check_out_at <> new_expected_check_out_at),
    CHECK (new_expected_check_out_at > operated_at)
);
CREATE INDEX ix_stay_extensions_history ON stay_extensions(stay_record_id, id DESC);
CREATE FUNCTION validate_stay_extension_fact() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM stay_records s JOIN stay_room_segments seg ON seg.stay_record_id = s.id
        WHERE s.id = NEW.stay_record_id AND seg.id = NEW.segment_id AND seg.exited_at IS NULL
          AND s.status = 'IN_HOUSE' AND s.version = NEW.stay_version
          AND s.expected_check_out_at = NEW.new_expected_check_out_at
          AND NEW.operated_at >= seg.entered_at AND NEW.new_expected_check_out_at > s.check_in_at
    ) THEN RAISE EXCEPTION 'Inconsistent stay extension fact' USING ERRCODE = '23514'; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER stay_extension_fact BEFORE INSERT ON stay_extensions
    FOR EACH ROW EXECUTE FUNCTION validate_stay_extension_fact();

ALTER TABLE idempotency_requests ADD COLUMN result_stay_extension_id BIGINT REFERENCES stay_extensions(id) ON DELETE RESTRICT;
ALTER TABLE idempotency_requests DROP CONSTRAINT idempotency_requests_operation_check;
ALTER TABLE idempotency_requests ADD CONSTRAINT idempotency_requests_operation_check CHECK (operation IN (
    'CHECK_IN','CHECK_OUT','HK_MANUAL_CREATE','HK_CLAIM','HK_ASSIGN','HK_REASSIGN','HK_START','HK_COMPLETE','HK_BATCH_ASSIGN',
    'ISSUE_REPORT','ISSUE_START','ISSUE_RESOLVE','ISSUE_SEVERITY','MAINTENANCE_STOP','MAINTENANCE_RESUME','ROOM_CHANGE','STAY_EXTEND'
));
-- Preserve all previous result-kind checks while separating extension receipts from old kinds.
ALTER TABLE idempotency_requests DROP CONSTRAINT ck_request_result_kind;
ALTER TABLE idempotency_requests ADD CONSTRAINT ck_request_result_kind CHECK (
    (operation IN ('CHECK_IN','CHECK_OUT') AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL AND result_issue_log_id IS NULL AND result_maintenance_log_id IS NULL AND result_room_change_id IS NULL AND result_stay_extension_id IS NULL) OR
    (operation IN ('HK_MANUAL_CREATE','HK_CLAIM','HK_ASSIGN','HK_REASSIGN','HK_START','HK_COMPLETE') AND result_stay_id IS NULL AND result_assignment_batch_id IS NULL AND result_issue_log_id IS NULL AND result_maintenance_log_id IS NULL AND result_room_change_id IS NULL AND result_stay_extension_id IS NULL) OR
    (operation = 'HK_BATCH_ASSIGN' AND result_stay_id IS NULL AND result_task_log_id IS NULL AND result_issue_log_id IS NULL AND result_maintenance_log_id IS NULL AND result_room_change_id IS NULL AND result_stay_extension_id IS NULL) OR
    (operation IN ('ISSUE_REPORT','ISSUE_START','ISSUE_RESOLVE','ISSUE_SEVERITY') AND result_stay_id IS NULL AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL AND result_maintenance_log_id IS NULL AND result_room_change_id IS NULL AND result_stay_extension_id IS NULL) OR
    (operation IN ('MAINTENANCE_STOP','MAINTENANCE_RESUME') AND result_stay_id IS NULL AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL AND result_issue_log_id IS NULL AND result_room_change_id IS NULL AND result_stay_extension_id IS NULL) OR
    (operation = 'ROOM_CHANGE' AND result_stay_id IS NULL AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL AND result_issue_log_id IS NULL AND result_maintenance_log_id IS NULL AND result_stay_extension_id IS NULL) OR
    (operation = 'STAY_EXTEND' AND result_stay_id IS NULL AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL AND result_issue_log_id IS NULL AND result_maintenance_log_id IS NULL AND result_room_change_id IS NULL)
);
COMMENT ON TABLE stay_extensions IS 'Append-only departure-plan changes. No guest data, room release, cleaning task or financial fact.';
