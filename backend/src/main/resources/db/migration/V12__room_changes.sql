-- Phase 7: preserve the stay and guests; append room-use history.
CREATE TABLE room_changes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 stay_record_id BIGINT NOT NULL REFERENCES stay_records(id) ON DELETE RESTRICT,
 old_room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
 new_room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
 old_segment_id BIGINT NOT NULL UNIQUE,
 new_segment_id BIGINT NOT NULL UNIQUE,
 reason_type VARCHAR(20) NOT NULL CHECK(reason_type IN ('GUEST_REQUEST','ROOM_ISSUE','OTHER')),
 reason VARCHAR(1000) NOT NULL CHECK(length(trim(reason)) BETWEEN 1 AND 1000),
 issue_id BIGINT,
 changed_at TIMESTAMPTZ NOT NULL,
 operated_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 old_room_number VARCHAR(20) NOT NULL, new_room_number VARCHAR(20) NOT NULL,
 old_room_type_name VARCHAR(100) NOT NULL, new_room_type_name VARCHAR(100) NOT NULL,
 CHECK(old_room_id<>new_room_id AND old_segment_id<>new_segment_id),
 CHECK(issue_id IS NULL OR reason_type='ROOM_ISSUE'),
 FOREIGN KEY(old_segment_id,stay_record_id,old_room_id) REFERENCES stay_room_segments(id,stay_record_id,room_id) ON DELETE RESTRICT,
 FOREIGN KEY(new_segment_id,stay_record_id,new_room_id) REFERENCES stay_room_segments(id,stay_record_id,room_id) ON DELETE RESTRICT,
 FOREIGN KEY(issue_id,old_room_id) REFERENCES room_issues(id,room_id) ON DELETE RESTRICT,
 UNIQUE(id,stay_record_id,old_room_id,old_segment_id)
);
CREATE INDEX ix_room_changes_stay ON room_changes(stay_record_id,changed_at,id);
CREATE FUNCTION validate_room_change_fact() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM stay_room_segments a JOIN stay_room_segments b ON b.id=NEW.new_segment_id
 JOIN stay_records s ON s.id=NEW.stay_record_id
 WHERE a.id=NEW.old_segment_id AND a.exited_at=NEW.changed_at AND a.end_reason='ROOM_CHANGE'
 AND b.entered_at=NEW.changed_at AND b.exited_at IS NULL AND s.status='IN_HOUSE'
 AND a.room_number_snapshot=NEW.old_room_number AND b.room_number_snapshot=NEW.new_room_number
 AND a.room_type_name_snapshot=NEW.old_room_type_name AND b.room_type_name_snapshot=NEW.new_room_type_name)
 THEN RAISE EXCEPTION 'Inconsistent room change fact' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER room_change_fact BEFORE INSERT ON room_changes FOR EACH ROW EXECUTE FUNCTION validate_room_change_fact();

