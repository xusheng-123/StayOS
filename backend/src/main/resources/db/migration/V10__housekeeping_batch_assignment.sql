CREATE TABLE housekeeping_assignment_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    assignee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL,
    notes VARCHAR(1000) NOT NULL DEFAULT ''
);
ALTER TABLE housekeeping_tasks ADD CONSTRAINT uq_task_room_identity UNIQUE(id,room_id);
ALTER TABLE housekeeping_task_logs ADD CONSTRAINT uq_log_task_identity UNIQUE(id,task_id);
CREATE TABLE housekeeping_assignment_items (
    batch_id BIGINT NOT NULL REFERENCES housekeeping_assignment_batches(id) ON DELETE RESTRICT,
    room_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    room_number_snapshot VARCHAR(20) NOT NULL,
    creation_log_id BIGINT,
    assignment_log_id BIGINT NOT NULL UNIQUE,
    PRIMARY KEY(batch_id,room_id),
    UNIQUE(batch_id,task_id),
    FOREIGN KEY(task_id,room_id) REFERENCES housekeeping_tasks(id,room_id) ON DELETE RESTRICT,
    FOREIGN KEY(creation_log_id,task_id) REFERENCES housekeeping_task_logs(id,task_id) ON DELETE RESTRICT,
    FOREIGN KEY(assignment_log_id,task_id) REFERENCES housekeeping_task_logs(id,task_id) ON DELETE RESTRICT
);
ALTER TABLE idempotency_requests ADD COLUMN result_assignment_batch_id BIGINT REFERENCES housekeeping_assignment_batches(id) ON DELETE RESTRICT;
ALTER TABLE idempotency_requests DROP CONSTRAINT idempotency_requests_operation_check;
ALTER TABLE idempotency_requests ADD CONSTRAINT idempotency_requests_operation_check CHECK
    (operation IN ('CHECK_IN','CHECK_OUT','HK_MANUAL_CREATE','HK_CLAIM','HK_ASSIGN','HK_REASSIGN','HK_START','HK_COMPLETE','HK_BATCH_ASSIGN'));
ALTER TABLE idempotency_requests DROP CONSTRAINT ck_request_result_kind;
ALTER TABLE idempotency_requests ADD CONSTRAINT ck_request_result_kind CHECK (
    (operation IN ('CHECK_IN','CHECK_OUT') AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL)
    OR (operation='HK_BATCH_ASSIGN' AND result_stay_id IS NULL AND result_task_log_id IS NULL)
    OR (operation IN ('HK_MANUAL_CREATE','HK_CLAIM','HK_ASSIGN','HK_REASSIGN','HK_START','HK_COMPLETE')
        AND result_stay_id IS NULL AND result_assignment_batch_id IS NULL));
COMMENT ON TABLE housekeeping_assignment_batches IS 'Atomic assignment receipt, not a second task system. No guest data or full request body.';
COMMENT ON COLUMN idempotency_requests.operation IS 'HK_CLAIM retained for historical data only; new claims are forbidden in the service and HTTP API.';
