-- V2.0: billing foundation per guide section 11.
-- Single currency CNY; amounts are positive NUMERIC(18,2) with direction kept separate.
-- Charges, payments and events are append-only facts; history prices live only as snapshots.
-- Guest identity data is never copied into any billing table.

CREATE TABLE billing_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INT NOT NULL UNIQUE CHECK (version>=1),
    billing_cutoff_time TIME NOT NULL,
    checkout_deadline TIME,
    early_checkin_mode VARCHAR(20) NOT NULL CHECK (early_checkin_mode IN ('FULL_NIGHT','HOURLY','FREE','DECLINED')),
    late_checkout_mode VARCHAR(20) NOT NULL CHECK (late_checkout_mode IN ('FREE','HOURLY','FULL_NIGHT','DECLINED')),
    early_checkout_mode VARCHAR(20) NOT NULL CHECK (early_checkout_mode IN ('FULL_NIGHT','CREDIT_UNUSED','DECLINED')),
    room_change_price_mode VARCHAR(20) NOT NULL CHECK (room_change_price_mode IN ('BY_NEW_SEGMENT','ORIGINAL_PRICE','DECLINED')),
    extension_price_mode VARCHAR(20) NOT NULL CHECK (extension_price_mode IN ('CURRENT_RATE','RATE_AT_CHECKIN','DECLINED')),
    notes VARCHAR(500) CHECK (notes IS NULL OR length(trim(notes)) BETWEEN 1 AND 500),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Exactly one active policy version; opening a folio requires one (service-level gate).
CREATE UNIQUE INDEX uq_billing_policy_active ON billing_policies((1)) WHERE is_active;
COMMENT ON TABLE billing_policies IS 'Versioned hotel billing policies (cutoff, checkout and price-difference modes). Auto billing is refused while no active version exists.';

CREATE TABLE rate_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type_id BIGINT NOT NULL REFERENCES room_types(id) ON DELETE RESTRICT,
    plan_code VARCHAR(40) NOT NULL CHECK (length(trim(plan_code)) BETWEEN 1 AND 40),
    plan_name VARCHAR(60) NOT NULL CHECK (length(trim(plan_name)) BETWEEN 1 AND 60),
    currency CHAR(3) NOT NULL DEFAULT 'CNY' CHECK (currency='CNY'),
    pricing_unit VARCHAR(10) NOT NULL DEFAULT 'NIGHT' CHECK (pricing_unit='NIGHT'),
    nightly_price NUMERIC(18,2) NOT NULL CHECK (nightly_price>=0 AND nightly_price<=999999.99),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (room_type_id, plan_code)
);
CREATE INDEX ix_rate_plans_type ON rate_plans(room_type_id);
COMMENT ON TABLE rate_plans IS 'Future-facing price list per room type. Changes never rewrite posted history; charges carry their own snapshot.';

CREATE TABLE room_rate_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_plan_id BIGINT NOT NULL REFERENCES rate_plans(id) ON DELETE RESTRICT,
    stay_date DATE NOT NULL,
    nightly_price NUMERIC(18,2) NOT NULL CHECK (nightly_price>=0 AND nightly_price<=999999.99),
    updated_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (rate_plan_id, stay_date)
);
COMMENT ON TABLE room_rate_days IS 'Per-date price calendar overriding the plan default for that date only.';

CREATE TABLE service_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code VARCHAR(40) NOT NULL CHECK (length(trim(item_code)) BETWEEN 1 AND 40),
    item_name VARCHAR(60) NOT NULL CHECK (length(trim(item_name)) BETWEEN 1 AND 60),
    currency CHAR(3) NOT NULL DEFAULT 'CNY' CHECK (currency='CNY'),
    pricing_unit VARCHAR(10) NOT NULL DEFAULT 'ITEM' CHECK (pricing_unit IN ('ITEM','TIME')),
    unit_price NUMERIC(18,2) NOT NULL CHECK (unit_price>=0 AND unit_price<=999999.99),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (item_code)
);
COMMENT ON TABLE service_catalog IS 'Goods and service price list. Price changes only affect future orders; orders snapshot name and price.';

CREATE TABLE service_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_record_id BIGINT NOT NULL REFERENCES stay_records(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED' CHECK (status IN ('REQUESTED','FULFILLED','CANCELLED')),
    note VARCHAR(500) CHECK (note IS NULL OR length(trim(note)) BETWEEN 1 AND 500),
    requested_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    fulfilled_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    fulfilled_at TIMESTAMPTZ,
    cancelled_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    cancelled_at TIMESTAMPTZ,
    cancel_reason VARCHAR(500) CHECK (cancel_reason IS NULL OR length(trim(cancel_reason)) BETWEEN 1 AND 500),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((status='REQUESTED' AND fulfilled_at IS NULL AND fulfilled_by IS NULL AND cancelled_at IS NULL AND cancelled_by IS NULL)
        OR (status='FULFILLED' AND fulfilled_at IS NOT NULL AND fulfilled_by IS NOT NULL AND cancelled_at IS NULL AND cancelled_by IS NULL)
        OR (status='CANCELLED' AND cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL AND fulfilled_at IS NULL AND fulfilled_by IS NULL))
);
CREATE INDEX ix_service_orders_stay ON service_orders(stay_record_id,id DESC);
COMMENT ON TABLE service_orders IS 'Per-stay consumption requests. Only fulfilment creates the unique charge source; cancelled orders are never billed.';

CREATE TABLE service_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES service_orders(id) ON DELETE RESTRICT,
    catalog_item_id BIGINT NOT NULL REFERENCES service_catalog(id) ON DELETE RESTRICT,
    item_name_snapshot VARCHAR(60) NOT NULL,
    unit_price_snapshot NUMERIC(18,2) NOT NULL CHECK (unit_price_snapshot>=0 AND unit_price_snapshot<=999999.99),
    currency_snapshot CHAR(3) NOT NULL CHECK (currency_snapshot='CNY'),
    quantity INT NOT NULL CHECK (quantity BETWEEN 1 AND 999),
    UNIQUE (order_id, catalog_item_id)
);

CREATE TABLE folios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_record_id BIGINT NOT NULL REFERENCES stay_records(id) ON DELETE RESTRICT,
    currency CHAR(3) NOT NULL DEFAULT 'CNY' CHECK (currency='CNY'),
    status VARCHAR(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
    pricing_status VARCHAR(20) NOT NULL CHECK (pricing_status IN ('PRICED','PRICING_REQUIRED')),
    charges_effective_from DATE,
    opened_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    closed_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (stay_record_id),
    CHECK ((status='OPEN' AND closed_at IS NULL AND closed_by IS NULL)
        OR (status='CLOSED' AND closed_at IS NOT NULL AND closed_by IS NOT NULL AND closed_at>=opened_at)),
    CHECK ((pricing_status='PRICING_REQUIRED') = (charges_effective_from IS NOT NULL))
);
CREATE INDEX ix_folios_status ON folios(status,id DESC);
COMMENT ON TABLE folios IS 'One folio per stay, single currency. Billing state is independent of stay state. PRICING_REQUIRED marks legacy stays whose pre-access history is not represented (never back-filled); charges_effective_from records the confirmed access date.';

CREATE TABLE folio_charges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_id BIGINT NOT NULL REFERENCES folios(id) ON DELETE RESTRICT,
    stay_record_id BIGINT NOT NULL REFERENCES stay_records(id) ON DELETE RESTRICT,
    room_segment_id BIGINT REFERENCES stay_room_segments(id) ON DELETE RESTRICT,
    business_date DATE NOT NULL,
    direction VARCHAR(10) NOT NULL CHECK (direction IN ('CHARGE','CREDIT')),
    category VARCHAR(20) NOT NULL CHECK (category IN ('ROOM_NIGHT','SERVICE','MANUAL','REVERSAL','CORRECTION')),
    name_snapshot VARCHAR(200) NOT NULL CHECK (length(trim(name_snapshot)) BETWEEN 1 AND 200),
    pricing_unit_snapshot VARCHAR(10) NOT NULL CHECK (pricing_unit_snapshot IN ('NIGHT','ITEM','UNIT')),
    quantity INT NOT NULL CHECK (quantity BETWEEN 1 AND 999),
    unit_price_snapshot NUMERIC(18,2) NOT NULL CHECK (unit_price_snapshot>=0 AND unit_price_snapshot<=999999.99),
    amount NUMERIC(18,2) NOT NULL CHECK (amount>0 AND amount<=99999999.99),
    currency CHAR(3) NOT NULL CHECK (currency='CNY'),
    policy_version INT,
    rate_plan_id BIGINT REFERENCES rate_plans(id) ON DELETE RESTRICT,
    catalog_item_id BIGINT REFERENCES service_catalog(id) ON DELETE RESTRICT,
    source_type VARCHAR(20) NOT NULL CHECK (source_type IN ('ROOM_NIGHT','SERVICE_ORDER','MANUAL','CREDIT','REVERSAL')),
    source_key VARCHAR(120) NOT NULL CHECK (length(source_key) BETWEEN 1 AND 120),
    reversal_of BIGINT REFERENCES folio_charges(id) ON DELETE RESTRICT,
    note VARCHAR(500) CHECK (note IS NULL OR length(trim(note)) BETWEEN 1 AND 500),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (quantity*unit_price_snapshot=amount),
    CHECK ((direction='CHARGE') = (reversal_of IS NULL)),
    CHECK ((direction='CHARGE') = (source_type IN ('ROOM_NIGHT','SERVICE_ORDER','MANUAL'))),
    CHECK ((direction='CREDIT') = (source_type IN ('CREDIT','REVERSAL'))),
    CHECK ((source_type='ROOM_NIGHT') = (category='ROOM_NIGHT')),
    CHECK ((source_type='SERVICE_ORDER') = (category='SERVICE')),
    CHECK ((source_type='MANUAL') = (category='MANUAL')),
    CHECK ((source_type='CREDIT') = (category='CORRECTION')),
    CHECK ((source_type='REVERSAL') = (category='REVERSAL')),
    CHECK ((category='ROOM_NIGHT') = (room_segment_id IS NOT NULL)),
    CHECK ((category='ROOM_NIGHT') = (policy_version IS NOT NULL)),
    CHECK ((category='ROOM_NIGHT') = (rate_plan_id IS NOT NULL)),
    CHECK ((category='SERVICE') = (catalog_item_id IS NOT NULL))
);
-- One charge per room night / per fulfilled order; credits reference originals without a stable key.
CREATE UNIQUE INDEX uq_folio_charge_source ON folio_charges(source_type,source_key) WHERE source_type IN ('ROOM_NIGHT','SERVICE_ORDER');
CREATE INDEX ix_folio_charges_folio ON folio_charges(folio_id,id);
CREATE INDEX ix_folio_charges_stay ON folio_charges(stay_record_id);
COMMENT ON TABLE folio_charges IS 'Append-only charge/credit facts. Amounts are positive, direction and category separate. Room nights and fulfilled services each have a unique source key so double posting is impossible; snapshots (name, unit, price, policy version) are frozen at posting.';

CREATE TABLE payment_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_id BIGINT NOT NULL REFERENCES folios(id) ON DELETE RESTRICT,
    direction VARCHAR(10) NOT NULL CHECK (direction IN ('RECEIPT','REFUND')),
    method VARCHAR(20) NOT NULL CHECK (method IN ('CASH','BANK_CARD','QR_PAYMENT','BANK_TRANSFER','OTHER')),
    purpose VARCHAR(20) CHECK (purpose IN ('PAYMENT','DEPOSIT')),
    amount NUMERIC(18,2) NOT NULL CHECK (amount>0 AND amount<=99999999.99),
    currency CHAR(3) NOT NULL CHECK (currency='CNY'),
    method_reference VARCHAR(120) CHECK (method_reference IS NULL OR length(trim(method_reference)) BETWEEN 1 AND 120),
    refund_of BIGINT REFERENCES payment_records(id) ON DELETE RESTRICT,
    note VARCHAR(500) CHECK (note IS NULL OR length(trim(note)) BETWEEN 1 AND 500),
    received_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((direction='RECEIPT' AND purpose IS NOT NULL AND refund_of IS NULL)
        OR (direction='REFUND' AND purpose IS NULL))
);
-- Non-cash references are unique per folio/method; cash receipts must not assume globally unique numbers.
CREATE UNIQUE INDEX uq_payment_reference ON payment_records(folio_id,direction,method,method_reference)
    WHERE method<>'CASH' AND method_reference IS NOT NULL;
CREATE INDEX ix_payment_records_folio ON payment_records(folio_id,id);
COMMENT ON TABLE payment_records IS 'Manually registered money facts for payments actually completed outside the system. Not gateway transactions; no legal invoice semantics.';

CREATE TABLE folio_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_id BIGINT NOT NULL REFERENCES folios(id) ON DELETE RESTRICT,
    event_type VARCHAR(20) NOT NULL CHECK (event_type IN ('OPENED','CLOSED','REOPENED')),
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    note VARCHAR(500) CHECK (note IS NULL OR length(trim(note)) BETWEEN 1 AND 500),
    detail JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(detail)='object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_folio_events_order ON folio_events(folio_id,id);

CREATE FUNCTION validate_folio_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.stay_record_id IS DISTINCT FROM OLD.stay_record_id OR NEW.currency IS DISTINCT FROM OLD.currency
            OR NEW.pricing_status IS DISTINCT FROM OLD.pricing_status
            OR NEW.charges_effective_from IS DISTINCT FROM OLD.charges_effective_from
            OR NEW.opened_by IS DISTINCT FROM OLD.opened_by OR NEW.opened_at IS DISTINCT FROM OLD.opened_at
            OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Folio coverage decision and opening facts are immutable' USING ERRCODE='23514'; END IF;
    IF (OLD.status,NEW.status) NOT IN (('OPEN','OPEN'),('OPEN','CLOSED'),('CLOSED','OPEN')) THEN
        RAISE EXCEPTION 'Invalid folio status transition' USING ERRCODE='23514'; END IF;
    IF NEW.status='CLOSED' AND (NEW.closed_at IS NULL OR NEW.closed_by IS NULL) THEN
        RAISE EXCEPTION 'Closing a folio requires closer and time' USING ERRCODE='23514'; END IF;
    IF NEW.status='OPEN' AND (NEW.closed_at IS NOT NULL OR NEW.closed_by IS NOT NULL) THEN
        RAISE EXCEPTION 'Reopened folio must clear closing facts' USING ERRCODE='23514'; END IF;
    IF NEW.version<OLD.version THEN RAISE EXCEPTION 'Folio version cannot move backwards' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER folio_update BEFORE UPDATE ON folios FOR EACH ROW EXECUTE FUNCTION validate_folio_update();

CREATE FUNCTION validate_service_order_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.stay_record_id IS DISTINCT FROM OLD.stay_record_id OR NEW.requested_by IS DISTINCT FROM OLD.requested_by
            OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Service order stay and requester are immutable' USING ERRCODE='23514'; END IF;
    IF (OLD.status,NEW.status) NOT IN (('REQUESTED','REQUESTED'),('REQUESTED','FULFILLED'),('REQUESTED','CANCELLED')) THEN
        RAISE EXCEPTION 'Invalid service order status transition' USING ERRCODE='23514'; END IF;
    IF NEW.fulfilled_at IS DISTINCT FROM OLD.fulfilled_at AND NOT (OLD.status='REQUESTED' AND NEW.status='FULFILLED') THEN
        RAISE EXCEPTION 'Service order fulfilment is immutable' USING ERRCODE='23514'; END IF;
    IF NEW.cancelled_at IS DISTINCT FROM OLD.cancelled_at AND NOT (OLD.status='REQUESTED' AND NEW.status='CANCELLED') THEN
        RAISE EXCEPTION 'Service order cancellation is immutable' USING ERRCODE='23514'; END IF;
    IF NEW.cancel_reason IS DISTINCT FROM OLD.cancel_reason AND NOT (OLD.status='REQUESTED' AND NEW.status='CANCELLED') THEN
        RAISE EXCEPTION 'Service order cancellation reason is immutable' USING ERRCODE='23514'; END IF;
    IF NEW.version<OLD.version THEN RAISE EXCEPTION 'Service order version cannot move backwards' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER service_order_update BEFORE UPDATE ON service_orders FOR EACH ROW EXECUTE FUNCTION validate_service_order_update();

CREATE FUNCTION validate_service_order_item_edit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT status FROM service_orders WHERE id=COALESCE(NEW.order_id,OLD.order_id))<>'REQUESTED' THEN
        RAISE EXCEPTION 'Fulfilled or cancelled service orders are frozen' USING ERRCODE='23514'; END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$;
CREATE TRIGGER service_order_item_edit BEFORE INSERT OR UPDATE OR DELETE ON service_order_items
    FOR EACH ROW EXECUTE FUNCTION validate_service_order_item_edit();

CREATE FUNCTION validate_folio_charge_insert() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE folio RECORD; original RECORD;
BEGIN
    SELECT status,stay_record_id INTO folio FROM folios WHERE id=NEW.folio_id;
    IF folio IS NULL OR folio.status<>'OPEN' THEN
        RAISE EXCEPTION 'Closed or missing folio accepts no charges' USING ERRCODE='23514'; END IF;
    IF NEW.stay_record_id<>folio.stay_record_id THEN
        RAISE EXCEPTION 'Charge must belong to the folio stay' USING ERRCODE='23514'; END IF;
    IF NEW.reversal_of IS NOT NULL THEN
        SELECT folio_id,direction INTO original FROM folio_charges WHERE id=NEW.reversal_of;
        IF original IS NULL OR original.folio_id<>NEW.folio_id OR original.direction<>'CHARGE' THEN
            RAISE EXCEPTION 'Credit must reverse a charge of the same folio' USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER folio_charge_insert BEFORE INSERT ON folio_charges FOR EACH ROW EXECUTE FUNCTION validate_folio_charge_insert();

CREATE FUNCTION validate_payment_record_insert() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE original RECORD;
BEGIN
    IF (SELECT status FROM folios WHERE id=NEW.folio_id)<>'OPEN' THEN
        RAISE EXCEPTION 'Closed folio accepts no payments' USING ERRCODE='23514'; END IF;
    IF NEW.refund_of IS NOT NULL THEN
        SELECT folio_id,direction INTO original FROM payment_records WHERE id=NEW.refund_of;
        IF original IS NULL OR original.folio_id<>NEW.folio_id OR original.direction<>'RECEIPT' THEN
            RAISE EXCEPTION 'Refund must reference a receipt of the same folio' USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER payment_record_insert BEFORE INSERT ON payment_records FOR EACH ROW EXECUTE FUNCTION validate_payment_record_insert();

CREATE FUNCTION prevent_billing_fact_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Billing facts are append-only history' USING ERRCODE='23514';
END $$;
CREATE TRIGGER folio_charges_append_only BEFORE UPDATE OR DELETE ON folio_charges
    FOR EACH ROW EXECUTE FUNCTION prevent_billing_fact_mutation();
CREATE TRIGGER payment_records_append_only BEFORE UPDATE OR DELETE ON payment_records
    FOR EACH ROW EXECUTE FUNCTION prevent_billing_fact_mutation();
CREATE TRIGGER folio_events_append_only BEFORE UPDATE OR DELETE ON folio_events
    FOR EACH ROW EXECUTE FUNCTION prevent_billing_fact_mutation();

