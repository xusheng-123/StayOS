    legacy_nulls := 'result_stay_id IS NULL AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL'
        || ' AND result_issue_log_id IS NULL AND result_maintenance_log_id IS NULL AND result_room_change_id IS NULL'
        || ' AND result_stay_extension_id IS NULL AND result_guest_correction_id IS NULL AND result_handover_id IS NULL';
