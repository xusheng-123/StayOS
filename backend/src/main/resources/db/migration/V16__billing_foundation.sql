        || '(operation NOT IN (''FOLIO_OPEN'',''FOLIO_CLOSE'',''FOLIO_REOPEN'',''CHARGE_POST'',''CHARGE_ADJUST'',''SERVICE_ORDER_CREATE'',''SERVICE_ORDER_FULFILL'',''SERVICE_ORDER_CANCEL'',''PAYMENT_RECEIVE'',''PAYMENT_REFUND'')'
        || ' AND result_folio_id IS NULL AND result_folio_charge_id IS NULL AND result_service_order_id IS NULL AND result_payment_record_id IS NULL AND '
        || substring(previous_check FROM 7) || ') '
        || 'OR (operation IN (''FOLIO_OPEN'',''FOLIO_CLOSE'',''FOLIO_REOPEN'') AND result_folio_charge_id IS NULL'
        || ' AND result_service_order_id IS NULL AND result_payment_record_id IS NULL AND ' || legacy_nulls || ') '
        || 'OR (operation IN (''CHARGE_POST'',''CHARGE_ADJUST'') AND result_folio_id IS NULL'
        || ' AND result_service_order_id IS NULL AND result_payment_record_id IS NULL AND ' || legacy_nulls || ') '
