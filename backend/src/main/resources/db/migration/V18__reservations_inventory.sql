-- V3.0: reservations and future inventory per guide section 13.
-- [arrivalDate, departureDate) half-open night spans; one reservation books one room type for one or more nights,
-- the concrete room number is assigned separately and stays advisory until check-in consumes RoomEligibility.
-- inventory_days.sold counts ONLY not-yet-checked-in reservation occupancy; check-in releases the counter and the
-- occupancy transfers to the live stay segment, so a night is never counted twice. Stays/extensions/room changes
-- express their own footprint through segments, never by touching sold.

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arrival_date DATE NOT NULL,
    departure_date DATE NOT NULL CHECK (departure_date>arrival_date),
    room_type_id BIGINT NOT NULL REFERENCES room_types(id) ON DELETE RESTRICT,
    status VARCHAR(12) NOT NULL DEFAULT 'HELD' CHECK (status IN ('HELD','CONFIRMED','CANCELLED','NO_SHOW','CHECKED_IN')),
    source VARCHAR(20) NOT NULL CHECK (source IN ('PHONE','WALK_IN','OTA','OTHER')),
    external_ref VARCHAR(120) CHECK (external_ref IS NULL OR length(trim(external_ref)) BETWEEN 1 AND 120),
    contact_name VARCHAR(100) NOT NULL CHECK (length(trim(contact_name)) BETWEEN 1 AND 100),
    contact_phone_ciphertext VARCHAR(500),
    contact_phone_mask VARCHAR(100) NOT NULL DEFAULT '',
    contact_encryption_key_id VARCHAR(30) CHECK ((contact_phone_ciphertext IS NULL) = (contact_encryption_key_id IS NULL)),
    held_until TIMESTAMPTZ,
    confirmed_at TIMESTAMPTZ, confirmed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    cancelled_at TIMESTAMPTZ, cancelled_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    cancel_reason VARCHAR(500) CHECK (cancel_reason IS NULL OR length(trim(cancel_reason)) BETWEEN 1 AND 500),
    no_show_at TIMESTAMPTZ, no_show_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    checked_in_stay_id BIGINT UNIQUE REFERENCES stay_records(id) ON DELETE RESTRICT,
    assigned_room_id BIGINT REFERENCES rooms(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ, assigned_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (external_ref IS NULL OR external_ref=trim(external_ref)),
    -- Held reservations carry an explicit expiry; terminal states fix their facts once.
    CHECK ((status='HELD' AND held_until IS NOT NULL AND confirmed_at IS NULL AND confirmed_by IS NULL
              AND cancelled_at IS NULL AND cancelled_by IS NULL AND cancel_reason IS NULL
              AND no_show_at IS NULL AND no_show_by IS NULL AND checked_in_stay_id IS NULL)
        OR (status='CONFIRMED' AND confirmed_at IS NOT NULL AND confirmed_by IS NOT NULL
              AND cancelled_at IS NULL AND cancelled_by IS NULL AND cancel_reason IS NULL
              AND no_show_at IS NULL AND no_show_by IS NULL AND checked_in_stay_id IS NULL)
        OR (status='CANCELLED' AND cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL AND length(trim(cancel_reason))>0
              AND no_show_at IS NULL AND no_show_by IS NULL AND checked_in_stay_id IS NULL)
        OR (status='NO_SHOW' AND no_show_at IS NOT NULL AND no_show_by IS NOT NULL AND confirmed_at IS NOT NULL
              AND checked_in_stay_id IS NULL)
        OR (status='CHECKED_IN' AND checked_in_stay_id IS NOT NULL AND confirmed_at IS NOT NULL)),
    CHECK (assigned_room_id IS NULL OR (assigned_at IS NOT NULL AND assigned_by IS NOT NULL))
);
COMMENT ON TABLE reservations IS 'One booking = one room type over [arrival,departure). Room numbers are advisory assignments; real occupancy starts only via stay check-in. contact phone stays GuestProtection-encrypted; identity documents are captured at check-in, never here.';

CREATE INDEX ix_reservations_status_arrival ON reservations(status,arrival_date,id DESC);
CREATE INDEX ix_reservations_room_type ON reservations(room_type_id,arrival_date);
-- The same OTA/phone reference must never create a second booking.
CREATE UNIQUE INDEX uq_reservation_external_ref ON reservations(external_ref) WHERE external_ref IS NOT NULL;

CREATE TABLE reservation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    action VARCHAR(40) NOT NULL CHECK (action IN ('CREATE','MODIFY','CONFIRM','CANCEL','EXPIRE_RELEASE','NO_SHOW','ASSIGN_ROOM','CHECK_IN','DEPOSIT_RECEIVE','DEPOSIT_REFUND')),
    actor BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    detail VARCHAR(1000) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_reservation_events_reservation ON reservation_events(reservation_id,id);
COMMENT ON TABLE reservation_events IS 'Append-only audit trail of reservation transitions and inventory compensations.';

-- Per room-type per-night reservation counter. Rows are created lazily with INSERT ON CONFLICT and then locked
-- FOR UPDATE in (room_type_id, stay_date) order before validation; sold never goes negative, so a double release fails loudly.
CREATE TABLE inventory_days (
    room_type_id BIGINT NOT NULL REFERENCES room_types(id) ON DELETE RESTRICT,
    stay_date DATE NOT NULL,
    sold INT NOT NULL DEFAULT 0 CHECK (sold>=0),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (room_type_id,stay_date)
);
COMMENT ON TABLE inventory_days IS 'Reservation occupancy counter per room type and night. Availability = enabled rooms − live segment occupancy − sold − blocked, computed at read time.';

-- Planned out-of-service ranges for a room type. Existence semantics: one active range covering a night blocks new
-- sales for that type/night; overlapping ranges stay allowed because blocking is never summed.
CREATE TABLE inventory_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type_id BIGINT NOT NULL REFERENCES room_types(id) ON DELETE RESTRICT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL CHECK (end_date>start_date),
    reason VARCHAR(500) NOT NULL CHECK (length(trim(reason)) BETWEEN 1 AND 500),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    released_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    released_at TIMESTAMPTZ,
    CHECK ((released_at IS NULL AND released_by IS NULL)
        OR (released_at IS NOT NULL AND released_by IS NOT NULL AND released_at>=created_at))
);
CREATE INDEX ix_inventory_blocks_active ON inventory_blocks(room_type_id,start_date,end_date) WHERE released_at IS NULL;
COMMENT ON TABLE inventory_blocks IS 'Planned stop-sell ranges, distinct from room_maintenance_stops which are real-time room outages. Eligibility for a concrete room is still decided by RoomEligibility at check-in.';

-- ---------- reservation immutability ----------
CREATE FUNCTION validate_reservation_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status='CHECKED_IN' OR OLD.status='CANCELLED' OR OLD.status='NO_SHOW' THEN
        RAISE EXCEPTION 'finished reservations are immutable' USING ERRCODE='23514';
    END IF;
    IF NEW.status NOT IN ('HELD','CONFIRMED','CANCELLED','NO_SHOW','CHECKED_IN')
        OR (OLD.status='HELD' AND NEW.status NOT IN ('HELD','CONFIRMED','CANCELLED'))
        OR (OLD.status='CONFIRMED' AND NEW.status NOT IN ('CONFIRMED','CANCELLED','NO_SHOW','CHECKED_IN')) THEN
        RAISE EXCEPTION 'reservation status transition not allowed' USING ERRCODE='23514';
    END IF;
    IF OLD.status='HELD' AND NEW.status='HELD' AND (NEW.confirmed_at IS NOT NULL OR NEW.cancelled_at IS NOT NULL
        OR NEW.no_show_at IS NOT NULL OR NEW.checked_in_stay_id IS NOT NULL) THEN
        RAISE EXCEPTION 'terminal facts are set only on the matching transition' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER reservation_update BEFORE UPDATE ON reservations FOR EACH ROW EXECUTE FUNCTION validate_reservation_update();
CREATE TRIGGER reservation_events_append_only BEFORE UPDATE OR DELETE ON reservation_events
    FOR EACH ROW EXECUTE FUNCTION prevent_billing_fact_mutation();

-- ---------- payment_records: reservation deposits ----------
-- Deposits may attach to a reservation before any folio exists (folio_id NULL, reservation_id set). Folio opening
-- migrates the record by filling folio_id exactly once and KEEPS reservation_id so the money stays traceably linked
-- to the booking (duplicate-collection audits join on it); every other column stays immutable for the record's
-- lifetime. A record with no attachment at all is invalid.
ALTER TABLE payment_records ALTER COLUMN folio_id DROP NOT NULL;
ALTER TABLE payment_records ADD COLUMN reservation_id BIGINT REFERENCES reservations(id) ON DELETE RESTRICT;
ALTER TABLE payment_records ADD CONSTRAINT payment_records_attachment_check CHECK (
    folio_id IS NOT NULL OR reservation_id IS NOT NULL);
CREATE INDEX ix_payment_records_reservation ON payment_records(reservation_id) WHERE reservation_id IS NOT NULL;

CREATE FUNCTION guard_payment_record_migration() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    -- The only permitted UPDATE: attach an unlinked reservation deposit to its folio at folio opening.
    IF OLD.reservation_id IS NOT NULL AND OLD.folio_id IS NULL AND NEW.reservation_id IS NOT NULL
        AND NEW.folio_id IS NOT NULL
        AND NEW.direction IS NOT DISTINCT FROM OLD.direction AND NEW.method IS NOT DISTINCT FROM OLD.method
        AND NEW.purpose IS NOT DISTINCT FROM OLD.purpose AND NEW.amount IS NOT DISTINCT FROM OLD.amount
        AND NEW.currency IS NOT DISTINCT FROM OLD.currency
        AND NEW.method_reference IS NOT DISTINCT FROM OLD.method_reference
        AND NEW.refund_of IS NOT DISTINCT FROM OLD.refund_of AND NEW.note IS NOT DISTINCT FROM OLD.note
        AND NEW.received_by IS NOT DISTINCT FROM OLD.received_by AND NEW.received_at IS NOT DISTINCT FROM OLD.received_at
        AND NEW.cashier_shift_id IS NOT DISTINCT FROM OLD.cashier_shift_id
        AND NEW.reservation_id IS NOT DISTINCT FROM OLD.reservation_id THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'money facts are append-only; only folio opening may attach a reservation deposit' USING ERRCODE='23514';
END $$;
DROP TRIGGER payment_records_append_only ON payment_records;
CREATE TRIGGER payment_records_guard BEFORE UPDATE ON payment_records
    FOR EACH ROW EXECUTE FUNCTION guard_payment_record_migration();
CREATE TRIGGER payment_records_no_delete BEFORE DELETE ON payment_records
    FOR EACH ROW EXECUTE FUNCTION prevent_billing_fact_mutation();

