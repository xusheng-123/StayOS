-- V5.0 limited guest profiles: master customer records kept separate from the per-registration
-- snapshots in guests. Matching and merging are always human-verified; an identical name or a
-- shared phone number never implies the same person.

CREATE TABLE customer_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL CHECK (length(trim(display_name)) > 0),
    document_type VARCHAR(20) NOT NULL CHECK (document_type IN ('ID_CARD','PASSPORT','OTHER')),
    document_ciphertext VARCHAR(500) NOT NULL,
    document_mask VARCHAR(100) NOT NULL,
    phone_ciphertext VARCHAR(500),
    phone_mask VARCHAR(100) NOT NULL DEFAULT '',
    encryption_key_id VARCHAR(30) NOT NULL,
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DISABLED','MERGED')),
    merged_into_id BIGINT REFERENCES customer_profiles(id) ON DELETE RESTRICT,
    version BIGINT NOT NULL DEFAULT 1 CHECK (version>=1),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT customer_profiles_merge_target_check CHECK (merged_into_id IS NULL OR merged_into_id <> id),
    CONSTRAINT customer_profiles_merge_state_check CHECK ((status = 'MERGED') = (merged_into_id IS NOT NULL))
);
COMMENT ON TABLE customer_profiles IS 'Limited guest profile master data. Separated from per-stay guest snapshots; plaintext never leaves the encryption boundary and no bulk export exists.';

-- Human-verified links between profiles and per-stay guest snapshots. Linking and unlinking are
-- audited; the stay records and guest snapshots themselves are never modified by this module.
CREATE TABLE customer_profile_stays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL REFERENCES customer_profiles(id) ON DELETE RESTRICT,
    stay_record_id BIGINT NOT NULL REFERENCES stay_records(id) ON DELETE RESTRICT,
    guest_id BIGINT NOT NULL REFERENCES guests(id) ON DELETE RESTRICT,
    associated_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    associated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- One registration snapshot belongs to at most one profile; fixing a wrong match = unlink + link.
    UNIQUE (guest_id)
);
COMMENT ON TABLE customer_profile_stays IS 'Human-verified profile-to-stay links. History lives in stay_records; these rows only reference it.';

-- Merged is terminal: the merged row is kept for traceability and can never change status or target again.
CREATE FUNCTION validate_customer_profile_transition() RETURNS trigger AS $$
BEGIN
    IF OLD.status = 'MERGED' AND (NEW.status <> 'MERGED' OR NEW.merged_into_id IS DISTINCT FROM OLD.merged_into_id) THEN
        RAISE EXCEPTION 'merged customer profiles are terminal' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER customer_profile_transition BEFORE UPDATE ON customer_profiles
    FOR EACH ROW EXECUTE FUNCTION validate_customer_profile_transition();

-- Profiles are facts: rows are never deleted, only disabled or merged away.
CREATE FUNCTION refuse_customer_profile_delete() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'customer profiles are never deleted' USING ERRCODE='23514'; END $$ LANGUAGE plpgsql;
CREATE TRIGGER customer_profiles_no_delete BEFORE DELETE ON customer_profiles
    FOR EACH ROW EXECUTE FUNCTION refuse_customer_profile_delete();

