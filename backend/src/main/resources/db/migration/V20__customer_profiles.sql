ALTER TABLE idempotency_requests DROP CONSTRAINT idempotency_requests_operation_check;
ALTER TABLE idempotency_requests ADD CONSTRAINT idempotency_requests_operation_check CHECK (operation IN (
    'CHECK_IN','CHECK_OUT','HK_MANUAL_CREATE','HK_CLAIM','HK_ASSIGN','HK_REASSIGN','HK_START','HK_COMPLETE','HK_BATCH_ASSIGN',
    'ISSUE_REPORT','ISSUE_START','ISSUE_RESOLVE','ISSUE_SEVERITY','MAINTENANCE_STOP','MAINTENANCE_RESUME','ROOM_CHANGE','STAY_EXTEND','GUEST_CORRECT',
    'HANDOVER_CREATE','HANDOVER_SUBMIT','HANDOVER_ACKNOWLEDGE',
    'FOLIO_OPEN','FOLIO_CLOSE','FOLIO_REOPEN','CHARGE_POST','CHARGE_ADJUST',
    'SERVICE_ORDER_CREATE','SERVICE_ORDER_FULFILL','SERVICE_ORDER_CANCEL','PAYMENT_RECEIVE','PAYMENT_REFUND',
    'CASHIER_SHIFT_OPEN','CASHIER_SHIFT_SUBMIT','CASHIER_SHIFT_CONFIRM',
    'RESERVATION_CREATE','RESERVATION_MODIFY','RESERVATION_CONFIRM','RESERVATION_CANCEL','RESERVATION_NO_SHOW',
    'RESERVATION_ASSIGN_ROOM','RESERVATION_CHECK_IN','RESERVATION_EXPIRE_RELEASE','RESERVATION_DEPOSIT_RECEIVE','RESERVATION_DEPOSIT_REFUND',
    'INVENTORY_BLOCK_CREATE','INVENTORY_BLOCK_RELEASE',
    'CUSTOMER_PROFILE_CREATE','CUSTOMER_PROFILE_UPDATE','CUSTOMER_PROFILE_SET_STATUS','CUSTOMER_PROFILE_MERGE',
    'CUSTOMER_PROFILE_STAY_LINK','CUSTOMER_PROFILE_STAY_UNLINK'
));
DO $$ DECLARE previous_check TEXT; BEGIN
    SELECT pg_get_constraintdef(oid) INTO previous_check FROM pg_constraint
        WHERE conrelid='idempotency_requests'::regclass AND conname='ck_request_result_kind';
    ALTER TABLE idempotency_requests DROP CONSTRAINT ck_request_result_kind;
    EXECUTE 'ALTER TABLE idempotency_requests ADD CONSTRAINT ck_request_result_kind CHECK ('
        || '(operation NOT IN (''CUSTOMER_PROFILE_CREATE'',''CUSTOMER_PROFILE_UPDATE'',''CUSTOMER_PROFILE_SET_STATUS'',''CUSTOMER_PROFILE_MERGE'','
        || '''CUSTOMER_PROFILE_STAY_LINK'',''CUSTOMER_PROFILE_STAY_UNLINK'')'
        || ' AND result_customer_profile_id IS NULL AND ' || substring(previous_check FROM 7) || ') '
        || 'OR (operation IN (''CUSTOMER_PROFILE_CREATE'',''CUSTOMER_PROFILE_UPDATE'',''CUSTOMER_PROFILE_SET_STATUS'',''CUSTOMER_PROFILE_MERGE'','
        || '''CUSTOMER_PROFILE_STAY_LINK'',''CUSTOMER_PROFILE_STAY_UNLINK'')'
        || ' AND result_reservation_id IS NULL AND result_inventory_block_id IS NULL))';
END $$;
