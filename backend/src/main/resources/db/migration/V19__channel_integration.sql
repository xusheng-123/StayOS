-- V4.0: supplier-agnostic channel integration per guide section 14.
-- Vendor fields stop at the integration adapter; every column below is supplier-neutral.
-- Credentials live OUTSIDE Git: connections keep only environment references
-- (credential_ref / callback_secret_ref), never the secret itself; normal queries never return secrets.

CREATE TABLE channel_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code VARCHAR(30) NOT NULL CHECK (supplier_code IN ('SIMULATOR')),
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    -- BLOCKED_EXTERNAL is the guide-mandated state for real suppliers without sandbox/authorization facts.
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','PAUSED','BLOCKED_EXTERNAL')),
    base_url VARCHAR(300) CHECK (base_url IS NULL OR base_url LIKE 'http://127.0.0.1:%' OR base_url LIKE 'http://localhost:%' OR base_url LIKE 'https://%'),
    credential_ref VARCHAR(200) NOT NULL CHECK (length(trim(credential_ref)) BETWEEN 1 AND 200),
    callback_secret_ref VARCHAR(200) NOT NULL CHECK (length(trim(callback_secret_ref)) BETWEEN 1 AND 200),
    protocol_version VARCHAR(20) NOT NULL DEFAULT '1.0' CHECK (length(trim(protocol_version)) BETWEEN 1 AND 20),
    last_inbound_at TIMESTAMPTZ, last_outbound_at TIMESTAMPTZ, last_sync_at TIMESTAMPTZ,
    last_error TEXT CHECK (last_error IS NULL OR length(last_error) BETWEEN 1 AND 2000),
    notes VARCHAR(500) NOT NULL DEFAULT '',
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    -- Optimistic-lock version for connection edits (PATCH carries the version it read).
    version BIGINT NOT NULL DEFAULT 1 CHECK (version>=1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (name=trim(name) AND credential_ref=trim(credential_ref) AND callback_secret_ref=trim(callback_secret_ref))
);
CREATE UNIQUE INDEX uq_channel_connections_name ON channel_connections(name);

-- Polymorphic local target: kind ROOM_TYPE -> room_types.id, kind RATE_PLAN -> rate_plans.id; the service validates.
CREATE TABLE channel_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT NOT NULL REFERENCES channel_connections(id) ON DELETE RESTRICT,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('ROOM_TYPE','RATE_PLAN')),
    local_id BIGINT NOT NULL CHECK (local_id>0),
    external_code VARCHAR(120) NOT NULL CHECK (length(trim(external_code)) BETWEEN 1 AND 120),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (connection_id, kind, external_code),
    UNIQUE (connection_id, kind, local_id)
);

-- Persisted BEFORE processing (guide: 入站持久化后通过同一预订服务处理).
-- Supplier version/sequence protocol, never arrival time: an older sequence_no for a connection is OBSOLETE,
-- a duplicate external_event_id hits the unique index (409), signature failures never reach this table.
CREATE TABLE inbound_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT NOT NULL REFERENCES channel_connections(id) ON DELETE RESTRICT,
    external_event_id VARCHAR(120) NOT NULL CHECK (length(trim(external_event_id)) BETWEEN 1 AND 120),
    event_type VARCHAR(50) NOT NULL CHECK (event_type IN ('ORDER_CREATE','ORDER_MODIFY','ORDER_CANCEL','PRICE_UPDATE')),
    sequence_no BIGINT NOT NULL CHECK (sequence_no>=0),
    payload JSONB NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PROCESSED','OBSOLETE','MANUAL')),
    attempts INT NOT NULL DEFAULT 0 CHECK (attempts>=0),
    next_attempt_at TIMESTAMPTZ,
    last_error TEXT CHECK (last_error IS NULL OR length(last_error) BETWEEN 1 AND 2000),
    result_reservation_id BIGINT REFERENCES reservations(id) ON DELETE RESTRICT,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at TIMESTAMPTZ,
    UNIQUE (connection_id, external_event_id)
);
CREATE INDEX ix_inbound_events_pending ON inbound_events(status, next_attempt_at NULLS FIRST, id) WHERE status='PENDING';
CREATE INDEX ix_inbound_events_connection ON inbound_events(connection_id, sequence_no);

-- Written in the SAME local transaction as the business change (guide: 出站业务变更与 outbox 在一个本地事务).
-- The worker claims rows in id order without holding room/inventory locks; external HTTP never happens inside them.
CREATE TABLE outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT NOT NULL REFERENCES channel_connections(id) ON DELETE RESTRICT,
    aggregate_type VARCHAR(20) NOT NULL CHECK (aggregate_type IN ('RESERVATION','INVENTORY_BLOCK')),
    aggregate_id BIGINT NOT NULL CHECK (aggregate_id>0),
    event_type VARCHAR(40) NOT NULL CHECK (event_type IN ('RESERVATION_CREATED','RESERVATION_CONFIRMED','RESERVATION_MODIFIED','RESERVATION_CANCELLED','RESERVATION_CHECKED_IN','INVENTORY_BLOCKED','INVENTORY_RELEASED')),
    payload JSONB NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SENT','MANUAL')),
    attempts INT NOT NULL DEFAULT 0 CHECK (attempts>=0),
    next_attempt_at TIMESTAMPTZ,
    last_error TEXT CHECK (last_error IS NULL OR length(last_error) BETWEEN 1 AND 2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at TIMESTAMPTZ,
    CONSTRAINT outbox_events_sent_check CHECK ((status='SENT') = (sent_at IS NOT NULL))
);
CREATE INDEX ix_outbox_events_pending ON outbox_events(status, next_attempt_at NULLS FIRST, id) WHERE status='PENDING';
CREATE INDEX ix_outbox_events_connection ON outbox_events(connection_id, id);

-- Per-attempt facts for both directions; append-only history (no UPDATE/DELETE grant).
CREATE TABLE sync_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT NOT NULL REFERENCES channel_connections(id) ON DELETE RESTRICT,
    direction VARCHAR(15) NOT NULL CHECK (direction IN ('OUTBOUND','INBOUND_PROCESS')),
    event_kind VARCHAR(15) NOT NULL CHECK (event_kind IN ('OUTBOX','INBOUND')),
    event_id BIGINT NOT NULL CHECK (event_id>0),
    outcome VARCHAR(12) NOT NULL CHECK (outcome IN ('SUCCESS','FAILURE','SKIPPED')),
    detail VARCHAR(2000) CHECK (detail IS NULL OR length(detail) BETWEEN 1 AND 2000),
    duration_ms INT CHECK (duration_ms IS NULL OR duration_ms>=0),
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_sync_attempts_event ON sync_attempts(event_kind, event_id, id);

CREATE TABLE reconciliation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT NOT NULL REFERENCES channel_connections(id) ON DELETE RESTRICT,
    status VARCHAR(12) NOT NULL DEFAULT 'RUNNING' CHECK (status IN ('RUNNING','COMPLETED','FAILED')),
    checked_count INT NOT NULL DEFAULT 0 CHECK (checked_count>=0),
    missing_local_count INT NOT NULL DEFAULT 0 CHECK (missing_local_count>=0),
    missing_remote_count INT NOT NULL DEFAULT 0 CHECK (missing_remote_count>=0),
    mismatch_count INT NOT NULL DEFAULT 0 CHECK (mismatch_count>=0),
    detail JSONB NOT NULL DEFAULT '{}'::jsonb,
    last_error TEXT CHECK (last_error IS NULL OR length(last_error) BETWEEN 1 AND 2000),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    started_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT reconciliation_runs_finish_check CHECK ((status='RUNNING') = (finished_at IS NULL))
);
CREATE INDEX ix_reconciliation_runs_connection ON reconciliation_runs(connection_id, id);
