-- V1.2: each registration owns its guest snapshot; correction facts are append-only.
ALTER TABLE guests ADD COLUMN version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0);
ALTER TABLE stay_guests ADD CONSTRAINT uq_registration_guest UNIQUE (guest_id);
CREATE TABLE guest_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_record_id BIGINT NOT NULL,
    guest_id BIGINT NOT NULL,
    guest_version BIGINT NOT NULL CHECK (guest_version > 0),
    operator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reason VARCHAR(1000) NOT NULL CHECK (length(trim(reason)) BETWEEN 1 AND 1000),
    operated_at TIMESTAMPTZ NOT NULL,
    changed_fields JSONB NOT NULL CHECK (jsonb_typeof(changed_fields)='array' AND jsonb_array_length(changed_fields) BETWEEN 1 AND 4
        AND changed_fields <@ '["name","documentType","documentNumber","phone"]'::jsonb),
    before_summary JSONB NOT NULL CHECK (jsonb_typeof(before_summary)='object'),
    after_summary JSONB NOT NULL CHECK (jsonb_typeof(after_summary)='object'),
    before_ciphertext TEXT NOT NULL CHECK (before_ciphertext LIKE 'v1.%'),
    after_ciphertext TEXT NOT NULL CHECK (after_ciphertext LIKE 'v1.%'),
    UNIQUE (guest_id,guest_version),
    FOREIGN KEY (stay_record_id,guest_id) REFERENCES stay_guests(stay_record_id,guest_id) ON DELETE RESTRICT
);
CREATE INDEX ix_guest_corrections_history ON guest_corrections(stay_record_id,guest_id,id DESC);
CREATE FUNCTION validate_guest_correction_fact() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM guests g JOIN stay_guests sg ON sg.guest_id=g.id JOIN stay_records s ON s.id=sg.stay_record_id
        WHERE s.id=NEW.stay_record_id AND g.id=NEW.guest_id AND s.status='IN_HOUSE'
          AND g.version=NEW.guest_version AND NEW.operated_at>=s.check_in_at
          AND NEW.after_summary->>'documentType'=g.document_type
          AND NEW.after_summary->>'documentNumber'=g.document_mask
          AND NEW.after_summary->>'phone'=g.phone_mask
    ) THEN RAISE EXCEPTION 'Inconsistent guest correction fact' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guest_correction_fact BEFORE INSERT ON guest_corrections
    FOR EACH ROW EXECUTE FUNCTION validate_guest_correction_fact();
ALTER TABLE idempotency_requests ADD COLUMN result_guest_correction_id BIGINT REFERENCES guest_corrections(id) ON DELETE RESTRICT;
ALTER TABLE idempotency_requests DROP CONSTRAINT idempotency_requests_operation_check;
ALTER TABLE idempotency_requests ADD CONSTRAINT idempotency_requests_operation_check CHECK (operation IN (
    'CHECK_IN','CHECK_OUT','HK_MANUAL_CREATE','HK_CLAIM','HK_ASSIGN','HK_REASSIGN','HK_START','HK_COMPLETE','HK_BATCH_ASSIGN',
    'ISSUE_REPORT','ISSUE_START','ISSUE_RESOLVE','ISSUE_SEVERITY','MAINTENANCE_STOP','MAINTENANCE_RESUME','ROOM_CHANGE','STAY_EXTEND','GUEST_CORRECT'
));
-- Wrap the previous CHECK to retain every existing result-kind restriction.
DO $$ DECLARE previous_check TEXT; BEGIN
    SELECT pg_get_constraintdef(oid) INTO previous_check FROM pg_constraint
        WHERE conrelid='idempotency_requests'::regclass AND conname='ck_request_result_kind';
    ALTER TABLE idempotency_requests DROP CONSTRAINT ck_request_result_kind;
    EXECUTE 'ALTER TABLE idempotency_requests ADD CONSTRAINT ck_request_result_kind CHECK ((operation <> ''GUEST_CORRECT'' AND result_guest_correction_id IS NULL AND '
        || substring(previous_check FROM 7) || ') OR (operation=''GUEST_CORRECT'' AND result_stay_id IS NULL AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL AND result_issue_log_id IS NULL AND result_maintenance_log_id IS NULL AND result_room_change_id IS NULL AND result_stay_extension_id IS NULL))';
END $$;
COMMENT ON TABLE guest_corrections IS 'Append-only registration typo corrections. Full snapshots encrypted with StayOS/v1/guest-correction AAD; summaries are masked. No external registration reporting.';
