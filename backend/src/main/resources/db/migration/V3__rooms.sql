-- Incremental migration: authentication tables and existing accounts are untouched.
CREATE TABLE room_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code VARCHAR(50) NOT NULL CONSTRAINT uq_room_type_code UNIQUE,
    type_name VARCHAR(100) NOT NULL CHECK (length(trim(type_name)) > 0),
    description VARCHAR(2000) NOT NULL DEFAULT '',
    bed_description VARCHAR(200) NOT NULL DEFAULT '',
    suggested_occupancy INTEGER NOT NULL CHECK (suggested_occupancy BETWEEN 1 AND 20),
    enabled BOOLEAN NOT NULL DEFAULT true,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (type_code ~ '^[A-Z0-9][A-Z0-9_-]{0,49}$')
);
CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(20) NOT NULL CONSTRAINT uq_room_number UNIQUE,
    floor INTEGER NOT NULL CHECK (floor BETWEEN -99 AND 199 AND floor <> 0),
    room_type_id BIGINT NOT NULL REFERENCES room_types(id) ON DELETE RESTRICT,
    notes VARCHAR(2000) NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT true,
    cleaning_status VARCHAR(20) NOT NULL DEFAULT 'DIRTY'
        CHECK (cleaning_status IN ('CLEAN', 'DIRTY', 'CLEANING', 'INSPECTION')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (room_number ~ '^[A-Z0-9][A-Z0-9_-]{0,19}$')
);
CREATE INDEX ix_rooms_type_floor ON rooms(room_type_id, floor);
CREATE INDEX ix_rooms_floor ON rooms(floor);

-- No occupancy, cleaning-task or issue modules exist in stage 2.
-- Later migrations MUST replace this view using the actual business records.
-- Never add a second, independently editable copy of those facts to rooms.
CREATE VIEW room_operational_facts AS
SELECT id AS room_id, false AS occupied, false AS has_blocking_issue,
       false AS has_open_cleaning_task, false AS has_usage_history
FROM rooms;
COMMENT ON VIEW room_operational_facts IS
'Stage 2 has no stays/issues/tasks. Replace by derived business facts when those modules are implemented.';

-- Single source for availability in lists, details, filters and statistics.
CREATE VIEW room_status AS
SELECT r.*,
       f.occupied, f.has_blocking_issue, f.has_open_cleaning_task, f.has_usage_history,
       CASE WHEN f.occupied THEN 'OCCUPIED' ELSE 'VACANT' END AS occupancy_status,
       CASE WHEN f.has_blocking_issue THEN 'OUT_OF_SERVICE' ELSE 'NORMAL' END AS maintenance_status,
       CASE WHEN r.enabled THEN 'ENABLED' ELSE 'DISABLED' END AS enabled_status,
       (r.enabled AND NOT f.occupied AND r.cleaning_status = 'CLEAN'
         AND NOT f.has_blocking_issue AND NOT f.has_open_cleaning_task) AS can_check_in,
       CASE
         WHEN NOT r.enabled THEN 'DISABLED'
         WHEN f.occupied THEN 'OCCUPIED'
         WHEN f.has_blocking_issue THEN 'OUT_OF_SERVICE'
         WHEN r.cleaning_status = 'CLEANING' THEN 'CLEANING'
         WHEN r.cleaning_status = 'INSPECTION' THEN 'INSPECTION'
         WHEN r.cleaning_status = 'DIRTY' THEN 'DIRTY'
         WHEN f.has_open_cleaning_task THEN 'UNAVAILABLE'
         ELSE 'VACANT_CLEAN'
       END AS availability
FROM rooms r JOIN room_operational_facts f ON f.room_id = r.id;
