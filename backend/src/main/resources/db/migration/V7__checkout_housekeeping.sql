-- Extend the existing idempotency protocol; never rewrite a historical migration.
ALTER TABLE idempotency_requests DROP CONSTRAINT idempotency_requests_operation_check;
ALTER TABLE idempotency_requests ADD CONSTRAINT idempotency_requests_operation_check
    CHECK (operation IN ('CHECK_IN','CHECK_OUT'));

CREATE TABLE housekeeping_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    task_type VARCHAR(30) NOT NULL CHECK (task_type='CHECKOUT_CLEANING'),
    source VARCHAR(30) NOT NULL CHECK (source='CHECKOUT'),
    source_id BIGINT NOT NULL,
    stay_record_id BIGINT NOT NULL REFERENCES stay_records(id) ON DELETE RESTRICT,
    room_segment_id BIGINT NOT NULL REFERENCES stay_room_segments(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status='PENDING'),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    CONSTRAINT uq_housekeeping_source UNIQUE(source,source_id),
    CONSTRAINT uq_housekeeping_checkout_segment UNIQUE(room_segment_id),
    CHECK (source_id=stay_record_id)
);
-- A task must refer to the exact room/stay/segment tuple, not three unrelated rows.
ALTER TABLE stay_room_segments ADD CONSTRAINT uq_segment_business_reference UNIQUE(id,stay_record_id,room_id);
ALTER TABLE housekeeping_tasks ADD CONSTRAINT fk_task_segment_business
    FOREIGN KEY(room_segment_id,stay_record_id,room_id)
    REFERENCES stay_room_segments(id,stay_record_id,room_id) ON DELETE RESTRICT;
CREATE INDEX ix_housekeeping_pending_time ON housekeeping_tasks(status,created_at DESC,id DESC);
CREATE INDEX ix_housekeeping_room ON housekeeping_tasks(room_id);
COMMENT ON TABLE housekeeping_tasks IS
'Stage 4: automatic checkout cleaning, read only. No guest data or duplicate cleaning state. Future task transitions require incremental migrations.';

CREATE OR REPLACE VIEW room_operational_facts AS
SELECT r.id AS room_id,
       EXISTS(SELECT 1 FROM stay_room_segments s WHERE s.room_id=r.id AND s.exited_at IS NULL) AS occupied,
       false AS has_blocking_issue,
       EXISTS(SELECT 1 FROM housekeeping_tasks t WHERE t.room_id=r.id AND t.status='PENDING') AS has_open_cleaning_task,
       EXISTS(SELECT 1 FROM stay_room_segments s WHERE s.room_id=r.id) AS has_usage_history
FROM rooms r;
COMMENT ON VIEW room_operational_facts IS
'Occupancy/history from segments, open tasks from housekeeping_tasks; issue module still absent. Cleaning is stored only in rooms.cleaning_status.';
