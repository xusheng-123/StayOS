CREATE OR REPLACE VIEW room_operational_facts AS
SELECT r.id room_id,
 EXISTS(SELECT 1 FROM stay_room_segments s WHERE s.room_id=r.id AND s.exited_at IS NULL) occupied,
 (EXISTS(SELECT 1 FROM room_issues i WHERE i.room_id=r.id AND i.severity='CRITICAL' AND i.status<>'RESOLVED') OR
 EXISTS(SELECT 1 FROM room_maintenance_stops m WHERE m.room_id=r.id AND m.resumed_at IS NULL)) has_blocking_issue,
 EXISTS(SELECT 1 FROM housekeeping_tasks t WHERE t.room_id=r.id AND t.status IN ('PENDING','IN_PROGRESS')) has_open_cleaning_task,
 EXISTS(SELECT 1 FROM stay_room_segments s WHERE s.room_id=r.id) has_usage_history FROM rooms r;

CREATE OR REPLACE VIEW room_status AS
SELECT r.*,
       f.occupied, f.has_blocking_issue, f.has_open_cleaning_task, f.has_usage_history,
       CASE WHEN f.occupied THEN 'OCCUPIED' ELSE 'VACANT' END AS occupancy_status,
       CASE WHEN f.has_blocking_issue THEN 'OUT_OF_SERVICE' ELSE 'NORMAL' END AS maintenance_status,
       CASE WHEN r.enabled THEN 'ENABLED' ELSE 'DISABLED' END AS enabled_status,
       (r.enabled AND NOT f.occupied AND r.cleaning_status = 'CLEAN'
         AND NOT f.has_blocking_issue AND NOT f.has_open_cleaning_task) AS can_check_in,
       CASE
         WHEN NOT r.enabled THEN 'DISABLED'
         WHEN f.occupied THEN 'OCCUPIED'
         WHEN f.has_blocking_issue THEN 'OUT_OF_SERVICE'
         WHEN r.cleaning_status = 'CLEANING' THEN 'CLEANING'
         WHEN r.cleaning_status = 'INSPECTION' THEN 'INSPECTION'
         WHEN r.cleaning_status = 'DIRTY' THEN 'DIRTY'
         WHEN f.has_open_cleaning_task THEN 'UNAVAILABLE'
         ELSE 'VACANT_CLEAN'
       END AS availability,
       EXISTS(SELECT 1 FROM room_issues i WHERE i.room_id=r.id AND i.status<>'RESOLVED') AS has_open_issue,
       EXISTS(SELECT 1 FROM room_issues i WHERE i.room_id=r.id AND i.severity='CRITICAL' AND i.status<>'RESOLVED') AS has_critical_issue,
       EXISTS(SELECT 1 FROM room_maintenance_stops m WHERE m.room_id=r.id AND m.resumed_at IS NULL) AS has_manual_maintenance_stop
FROM rooms r JOIN room_operational_facts f ON f.room_id = r.id;
