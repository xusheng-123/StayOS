-- Phase 6: derived maintenance facts; previous migrations and room data are untouched.
CREATE TABLE room_issues (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
 issue_type VARCHAR(20) NOT NULL CHECK(issue_type IN ('FACILITY','ELECTRICAL','PLUMBING','SANITATION','SAFETY','OTHER')),
 severity VARCHAR(20) NOT NULL CHECK(severity IN ('LOW','MEDIUM','CRITICAL')),
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','IN_PROGRESS','RESOLVED')),
 description VARCHAR(2000) NOT NULL CHECK(length(trim(description)) BETWEEN 1 AND 2000),
 notes VARCHAR(1000) NOT NULL DEFAULT '',
 reported_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 reported_at TIMESTAMPTZ NOT NULL,
 started_by BIGINT REFERENCES users(id) ON DELETE RESTRICT, started_at TIMESTAMPTZ,
 resolved_by BIGINT REFERENCES users(id) ON DELETE RESTRICT, resolved_at TIMESTAMPTZ,
 resolution VARCHAR(1000) NOT NULL DEFAULT '', version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 CHECK ((started_by IS NULL)=(started_at IS NULL)),
 CHECK (started_at IS NULL OR started_at>=reported_at),
 CHECK ((status='OPEN' AND started_at IS NULL AND resolved_at IS NULL AND resolved_by IS NULL AND resolution='') OR
 (status='IN_PROGRESS' AND started_at IS NOT NULL AND resolved_at IS NULL AND resolved_by IS NULL AND resolution='') OR
 (status='RESOLVED' AND resolved_at IS NOT NULL AND resolved_by IS NOT NULL AND length(trim(resolution))>0 AND resolved_at>=coalesce(started_at,reported_at)))
);
CREATE INDEX ix_room_issues_open ON room_issues(room_id,severity) WHERE status<>'RESOLVED';
CREATE INDEX ix_room_issues_reporter ON room_issues(reported_by,id);
CREATE TABLE room_issue_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_id BIGINT NOT NULL REFERENCES room_issues(id) ON DELETE RESTRICT,
 action VARCHAR(20) NOT NULL CHECK(action IN ('REPORT','START','RESOLVE','SEVERITY')),
 from_status VARCHAR(20) CHECK(from_status IN ('OPEN','IN_PROGRESS')),
 to_status VARCHAR(20) NOT NULL CHECK(to_status IN ('OPEN','IN_PROGRESS','RESOLVED')),
 from_severity VARCHAR(20) CHECK(from_severity IN ('LOW','MEDIUM','CRITICAL')),
 to_severity VARCHAR(20) NOT NULL CHECK(to_severity IN ('LOW','MEDIUM','CRITICAL')),
 operator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 operated_at TIMESTAMPTZ NOT NULL, reason VARCHAR(2000) NOT NULL DEFAULT '',
 issue_version BIGINT NOT NULL CHECK(issue_version>=0), UNIQUE(issue_id,issue_version),
 CHECK ((action='REPORT' AND from_status IS NULL AND from_severity IS NULL AND to_status='OPEN' AND issue_version=0) OR
 (action='START' AND from_status='OPEN' AND to_status='IN_PROGRESS' AND from_severity=to_severity) OR
 (action='RESOLVE' AND from_status IN ('OPEN','IN_PROGRESS') AND to_status='RESOLVED' AND from_severity=to_severity AND length(trim(reason))>0) OR
 (action='SEVERITY' AND from_status=to_status AND from_severity<>to_severity AND length(trim(reason))>0))
);
CREATE TABLE room_maintenance_stops (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
 issue_id BIGINT REFERENCES room_issues(id) ON DELETE RESTRICT,
 reason VARCHAR(1000) NOT NULL CHECK(length(trim(reason))>0),
 stopped_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT, stopped_at TIMESTAMPTZ NOT NULL,
 resumed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT, resumed_at TIMESTAMPTZ,
 resume_reason VARCHAR(1000) NOT NULL DEFAULT '',
 CHECK ((resumed_at IS NULL AND resumed_by IS NULL AND resume_reason='') OR
 (resumed_at IS NOT NULL AND resumed_by IS NOT NULL AND length(trim(resume_reason))>0 AND resumed_at>=stopped_at))
);
ALTER TABLE room_issues ADD CONSTRAINT uq_issue_room_identity UNIQUE(id,room_id);
ALTER TABLE room_maintenance_stops ADD CONSTRAINT fk_stop_issue_room FOREIGN KEY(issue_id,room_id) REFERENCES room_issues(id,room_id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX uq_room_active_maintenance_stop ON room_maintenance_stops(room_id) WHERE resumed_at IS NULL;
CREATE TABLE room_maintenance_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 stop_id BIGINT NOT NULL REFERENCES room_maintenance_stops(id) ON DELETE RESTRICT,
 action VARCHAR(20) NOT NULL CHECK(action IN ('STOP','RESUME')),
 operator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 operated_at TIMESTAMPTZ NOT NULL, reason VARCHAR(1000) NOT NULL CHECK(length(trim(reason))>0),
 UNIQUE(stop_id,action)
);
CREATE FUNCTION enforce_room_issue_transition() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.room_id<>NEW.room_id OR OLD.reported_by<>NEW.reported_by OR OLD.reported_at<>NEW.reported_at OR OLD.issue_type<>NEW.issue_type OR OLD.description<>NEW.description OR OLD.notes<>NEW.notes
 OR OLD.status='RESOLVED' OR NEW.version<>OLD.version+1
 OR NOT ((OLD.status=NEW.status AND OLD.severity<>NEW.severity) OR (OLD.status='OPEN' AND NEW.status IN ('IN_PROGRESS','RESOLVED') AND OLD.severity=NEW.severity) OR (OLD.status='IN_PROGRESS' AND NEW.status='RESOLVED' AND OLD.severity=NEW.severity))
 OR (OLD.started_at IS NOT NULL AND (OLD.started_at IS DISTINCT FROM NEW.started_at OR OLD.started_by IS DISTINCT FROM NEW.started_by))
 THEN RAISE EXCEPTION 'Illegal room issue transition' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER room_issue_transition BEFORE UPDATE ON room_issues FOR EACH ROW EXECUTE FUNCTION enforce_room_issue_transition();
