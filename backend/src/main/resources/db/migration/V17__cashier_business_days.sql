-- V2.1: cashier shifts, business days and daily close per guide section 12.
-- Money stays positive NUMERIC(18,2) with direction kept separate; expected/difference may go negative.
-- Reports are frozen snapshots; a closed day is never re-computed, later corrections land on the current day.
-- Cashier shifts are independent from V1.3 shift_handovers (which handle non-financial items).

CREATE TABLE business_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE NOT NULL UNIQUE,
    status VARCHAR(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
    policy_id BIGINT NOT NULL REFERENCES billing_policies(id) ON DELETE RESTRICT,
    closed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    closed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((status='OPEN' AND closed_at IS NULL AND closed_by IS NULL)
        OR (status='CLOSED' AND closed_at IS NOT NULL AND closed_by IS NOT NULL AND closed_at>=created_at))
);
COMMENT ON TABLE business_days IS 'Explicit business-day registry. Rows are created lazily with the active policy pinned; the stored policy cutoff attributes events to this day even if the policy changes later.';

CREATE TABLE cashier_shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE NOT NULL,
    operator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','SUBMITTED','CONFIRMED')),
    opened_float NUMERIC(18,2) NOT NULL CHECK (opened_float>=0 AND opened_float<=999999.99),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    counted_cash NUMERIC(18,2) CHECK (counted_cash IS NULL OR counted_cash>=0),
    difference_reason VARCHAR(500) CHECK (difference_reason IS NULL OR length(trim(difference_reason)) BETWEEN 1 AND 500),
    submitted_at TIMESTAMPTZ,
    confirmed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    confirmed_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((status='OPEN' AND submitted_at IS NULL AND counted_cash IS NULL AND difference_reason IS NULL AND confirmed_at IS NULL AND confirmed_by IS NULL)
        OR (status='SUBMITTED' AND submitted_at IS NOT NULL AND counted_cash IS NOT NULL AND confirmed_at IS NULL AND confirmed_by IS NULL)
        OR (status='CONFIRMED' AND submitted_at IS NOT NULL AND counted_cash IS NOT NULL AND confirmed_at IS NOT NULL AND confirmed_by IS NOT NULL AND confirmed_at>=submitted_at))
);
CREATE INDEX ix_cashier_shifts_operator ON cashier_shifts(operator_id,id DESC);
-- One drawer per cashier: a second OPEN shift for the same operator would make cash attribution ambiguous.
CREATE UNIQUE INDEX uq_cashier_shift_open ON cashier_shifts(operator_id) WHERE status='OPEN';
COMMENT ON TABLE cashier_shifts IS 'Cash drawer shift OPEN->SUBMITTED->CONFIRMED. Cash receipts/refunds attach to the receiver''s OPEN shift at insert time; counts never rewrite posted payments.';

CREATE TABLE cash_counts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cashier_shift_id BIGINT NOT NULL REFERENCES cashier_shifts(id) ON DELETE RESTRICT,
    expected_cash NUMERIC(18,2) NOT NULL,
    counted_cash NUMERIC(18,2) NOT NULL CHECK (counted_cash>=0 AND counted_cash<=999999.99),
    difference NUMERIC(18,2) NOT NULL,
    difference_reason VARCHAR(500) CHECK (difference_reason IS NULL OR length(trim(difference_reason)) BETWEEN 1 AND 500),
    counted_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    counted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (difference=counted_cash-expected_cash),
    CHECK (difference=0 OR difference_reason IS NOT NULL)
);
COMMENT ON TABLE cash_counts IS 'Immutable count record written when a shift is submitted; the shift row keeps the submitted values for display.';

CREATE TABLE daily_close_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE NOT NULL REFERENCES business_days(business_date) ON DELETE RESTRICT,
    status VARCHAR(10) NOT NULL CHECK (status IN ('RUNNING','COMPLETED','FAILED')),
    started_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    steps_done INT NOT NULL DEFAULT 0 CHECK (steps_done BETWEEN 0 AND 4),
    last_step VARCHAR(40),
    failure_reason VARCHAR(1000) CHECK (failure_reason IS NULL OR length(trim(failure_reason)) BETWEEN 1 AND 1000),
    CHECK ((status='RUNNING' AND finished_at IS NULL AND failure_reason IS NULL)
        OR (status='COMPLETED' AND finished_at IS NOT NULL AND failure_reason IS NULL)
        OR (status='FAILED' AND finished_at IS NOT NULL AND failure_reason IS NOT NULL))
);
CREATE INDEX ix_daily_close_runs_date ON daily_close_runs(business_date,id DESC);
-- Single close per day at database level: only one RUNNING run per business date can exist.
CREATE UNIQUE INDEX uq_daily_close_running ON daily_close_runs(business_date) WHERE status='RUNNING';
COMMENT ON TABLE daily_close_runs IS 'Manual close batches: verify room fees -> reconcile charges/funds -> freeze report -> mark day CLOSED. A FAILED run leaves the day OPEN; a retry re-verifies everything.';

CREATE TABLE daily_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE NOT NULL UNIQUE REFERENCES business_days(business_date) ON DELETE RESTRICT,
    run_id BIGINT NOT NULL REFERENCES daily_close_runs(id) ON DELETE RESTRICT,
    snapshot JSONB NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE daily_reports IS 'Frozen report snapshot written only when a close run succeeds; includes denominators, data-gap markers and post-close adjustment traceability.';

-- Payments attach to the receiver''s OPEN cash shift at insert time; NULL for pre-V2.1 rows or shifts never opened.
ALTER TABLE payment_records ADD COLUMN cashier_shift_id BIGINT REFERENCES cashier_shifts(id) ON DELETE RESTRICT;
CREATE INDEX ix_payment_records_shift ON payment_records(cashier_shift_id) WHERE cashier_shift_id IS NOT NULL;

-- ---------- immutability triggers ----------
CREATE FUNCTION validate_cashier_shift_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status='CONFIRMED' THEN
        RAISE EXCEPTION 'confirmed cashier shifts are immutable' USING ERRCODE='23514';
    END IF;
    IF NEW.status NOT IN ('OPEN','SUBMITTED','CONFIRMED')
        OR (OLD.status='OPEN' AND NEW.status NOT IN ('OPEN','SUBMITTED'))
        OR (OLD.status='SUBMITTED' AND NEW.status<>'CONFIRMED') THEN
        RAISE EXCEPTION 'cashier shift status transition not allowed' USING ERRCODE='23514';
    END IF;
    IF OLD.status='OPEN' AND NEW.status='OPEN' AND (NEW.counted_cash IS NOT NULL OR NEW.submitted_at IS NOT NULL) THEN
        RAISE EXCEPTION 'count values are set only when submitting' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER cashier_shift_update BEFORE UPDATE ON cashier_shifts FOR EACH ROW EXECUTE FUNCTION validate_cashier_shift_update();

CREATE FUNCTION prevent_cashier_fact_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'cash records are append-only' USING ERRCODE='23514';
END $$;
CREATE TRIGGER cash_counts_append_only BEFORE UPDATE OR DELETE ON cash_counts
    FOR EACH ROW EXECUTE FUNCTION prevent_cashier_fact_mutation();
CREATE TRIGGER daily_reports_append_only BEFORE UPDATE OR DELETE ON daily_reports
    FOR EACH ROW EXECUTE FUNCTION prevent_cashier_fact_mutation();

CREATE FUNCTION validate_daily_close_run_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    -- Only RUNNING rows may be touched; they may bump progress or terminate once. Terminal rows are immutable.
    IF OLD.status<>'RUNNING' THEN
        RAISE EXCEPTION 'close runs are immutable after completion or failure' USING ERRCODE='23514';
    END IF;
    IF NEW.status NOT IN ('RUNNING','COMPLETED','FAILED') THEN
        RAISE EXCEPTION 'close run status not allowed' USING ERRCODE='23514';
    END IF;
    IF NEW.status='RUNNING' AND (NEW.finished_at IS NOT NULL OR NEW.failure_reason IS NOT NULL) THEN
        RAISE EXCEPTION 'progress updates must not terminate the run' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER daily_close_run_update BEFORE UPDATE ON daily_close_runs FOR EACH ROW EXECUTE FUNCTION validate_daily_close_run_update();
CREATE TRIGGER daily_close_runs_append_only BEFORE DELETE ON daily_close_runs
    FOR EACH ROW EXECUTE FUNCTION prevent_cashier_fact_mutation();

CREATE FUNCTION prevent_business_day_resurrection() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status='CLOSED' AND NEW.status<>'CLOSED' THEN
        RAISE EXCEPTION 'closed business days cannot be reopened in this version' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER business_day_update BEFORE UPDATE ON business_days FOR EACH ROW EXECUTE FUNCTION prevent_business_day_resurrection();

-- ---------- idempotency extension ----------
ALTER TABLE idempotency_requests ADD COLUMN result_cashier_shift_id BIGINT REFERENCES cashier_shifts(id) ON DELETE RESTRICT;
ALTER TABLE idempotency_requests DROP CONSTRAINT idempotency_requests_operation_check;
ALTER TABLE idempotency_requests ADD CONSTRAINT idempotency_requests_operation_check CHECK (operation IN (
    'CHECK_IN','CHECK_OUT','HK_MANUAL_CREATE','HK_CLAIM','HK_ASSIGN','HK_REASSIGN','HK_START','HK_COMPLETE','HK_BATCH_ASSIGN',
    'ISSUE_REPORT','ISSUE_START','ISSUE_RESOLVE','ISSUE_SEVERITY','MAINTENANCE_STOP','MAINTENANCE_RESUME','ROOM_CHANGE','STAY_EXTEND','GUEST_CORRECT',
    'HANDOVER_CREATE','HANDOVER_SUBMIT','HANDOVER_ACKNOWLEDGE',
    'FOLIO_OPEN','FOLIO_CLOSE','FOLIO_REOPEN','CHARGE_POST','CHARGE_ADJUST',
    'SERVICE_ORDER_CREATE','SERVICE_ORDER_FULFILL','SERVICE_ORDER_CANCEL','PAYMENT_RECEIVE','PAYMENT_REFUND',
    'CASHIER_SHIFT_OPEN','CASHIER_SHIFT_SUBMIT','CASHIER_SHIFT_CONFIRM'
));
DO $$ DECLARE previous_check TEXT; legacy_nulls TEXT; BEGIN
    SELECT pg_get_constraintdef(oid) INTO previous_check FROM pg_constraint
        WHERE conrelid='idempotency_requests'::regclass AND conname='ck_request_result_kind';
    ALTER TABLE idempotency_requests DROP CONSTRAINT ck_request_result_kind;
    legacy_nulls := 'result_stay_id IS NULL AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL'
        || ' AND result_issue_log_id IS NULL AND result_maintenance_log_id IS NULL AND result_room_change_id IS NULL'
        || ' AND result_stay_extension_id IS NULL AND result_guest_correction_id IS NULL AND result_handover_id IS NULL'
        || ' AND result_folio_id IS NULL AND result_folio_charge_id IS NULL AND result_service_order_id IS NULL AND result_payment_record_id IS NULL';
    EXECUTE 'ALTER TABLE idempotency_requests ADD CONSTRAINT ck_request_result_kind CHECK ('
        || '(operation NOT IN (''CASHIER_SHIFT_OPEN'',''CASHIER_SHIFT_SUBMIT'',''CASHIER_SHIFT_CONFIRM'')'
        || ' AND result_cashier_shift_id IS NULL AND ' || substring(previous_check FROM 7) || ') '
        || 'OR (operation IN (''CASHIER_SHIFT_OPEN'',''CASHIER_SHIFT_SUBMIT'',''CASHIER_SHIFT_CONFIRM'') AND ' || legacy_nulls || '))';
END $$;
