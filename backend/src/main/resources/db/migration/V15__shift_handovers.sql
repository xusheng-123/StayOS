-- V1.3: non-financial shift handovers per FRONT_DESK / HOUSEKEEPING scope.
-- DRAFT -> SUBMITTED freezes summary and items; ACKNOWLEDGED is immutable history.
CREATE TABLE shift_handovers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope VARCHAR(20) NOT NULL CHECK (scope IN ('FRONT_DESK','HOUSEKEEPING')),
    handover_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    receiver_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    shift_start_at TIMESTAMPTZ NOT NULL,
    shift_end_at TIMESTAMPTZ NOT NULL,
    summary VARCHAR(2000) NOT NULL DEFAULT '' CHECK (length(summary)<=2000),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','SUBMITTED','ACKNOWLEDGED')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    submitted_at TIMESTAMPTZ,
    acknowledged_at TIMESTAMPTZ,
    acknowledged_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (receiver_id<>handover_by),
    CHECK (shift_end_at>shift_start_at),
    CHECK ((status='DRAFT' AND submitted_at IS NULL AND acknowledged_at IS NULL AND acknowledged_by IS NULL)
        OR (status='SUBMITTED' AND submitted_at IS NOT NULL AND acknowledged_at IS NULL AND acknowledged_by IS NULL)
        OR (status='ACKNOWLEDGED' AND submitted_at IS NOT NULL AND acknowledged_at IS NOT NULL AND acknowledged_by IS NOT NULL))
);
CREATE INDEX ix_shift_handovers_scope ON shift_handovers(scope,id DESC);
CREATE INDEX ix_shift_handovers_receiver ON shift_handovers(receiver_id,id DESC);

CREATE TABLE handover_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id BIGINT NOT NULL REFERENCES shift_handovers(id) ON DELETE RESTRICT,
    position INT NOT NULL CHECK (position BETWEEN 0 AND 49),
    category VARCHAR(30) NOT NULL CHECK (category IN ('OVERDUE_STAY','STRANDED_TASK','DELAYED_TASK','CRITICAL_ISSUE','MAINTENANCE_STOP','CUSTOM')),
    content VARCHAR(500) NOT NULL CHECK (length(trim(content)) BETWEEN 1 AND 500),
    source_id BIGINT,
    UNIQUE (handover_id,position)
);
CREATE INDEX ix_handover_items_order ON handover_items(handover_id,position);

CREATE TABLE handover_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id BIGINT NOT NULL REFERENCES shift_handovers(id) ON DELETE RESTRICT,
    event_type VARCHAR(20) NOT NULL CHECK (event_type IN ('CREATED','UPDATED','SUBMITTED','REASSIGNED','ACKNOWLEDGED')),
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reason VARCHAR(1000) CHECK (reason IS NULL OR length(trim(reason)) BETWEEN 1 AND 1000),
    detail JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(detail)='object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_handover_events_order ON handover_events(handover_id,id);

CREATE FUNCTION validate_shift_handover_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.scope IS DISTINCT FROM OLD.scope OR NEW.handover_by IS DISTINCT FROM OLD.handover_by
            OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Handover scope, creator and creation time are immutable' USING ERRCODE='23514'; END IF;
    IF OLD.status='ACKNOWLEDGED' THEN RAISE EXCEPTION 'Acknowledged handover is immutable' USING ERRCODE='23514'; END IF;
    IF (OLD.status,NEW.status) NOT IN (('DRAFT','DRAFT'),('DRAFT','SUBMITTED'),('SUBMITTED','SUBMITTED'),('SUBMITTED','ACKNOWLEDGED')) THEN
        RAISE EXCEPTION 'Invalid handover status transition' USING ERRCODE='23514'; END IF;
    IF OLD.status<>'DRAFT' AND (NEW.shift_start_at IS DISTINCT FROM OLD.shift_start_at
            OR NEW.shift_end_at IS DISTINCT FROM OLD.shift_end_at OR NEW.summary IS DISTINCT FROM OLD.summary) THEN
        RAISE EXCEPTION 'Submitted handover snapshot is frozen' USING ERRCODE='23514'; END IF;
    IF NEW.submitted_at IS DISTINCT FROM OLD.submitted_at AND NOT (OLD.status='DRAFT' AND NEW.status='SUBMITTED') THEN
        RAISE EXCEPTION 'Handover submit time is immutable' USING ERRCODE='23514'; END IF;
    IF (NEW.acknowledged_at IS DISTINCT FROM OLD.acknowledged_at OR NEW.acknowledged_by IS DISTINCT FROM OLD.acknowledged_by)
            AND NOT (OLD.status='SUBMITTED' AND NEW.status='ACKNOWLEDGED') THEN
        RAISE EXCEPTION 'Handover acknowledgement is immutable' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER shift_handover_update BEFORE UPDATE ON shift_handovers
    FOR EACH ROW EXECUTE FUNCTION validate_shift_handover_update();

CREATE FUNCTION validate_handover_item_edit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT status FROM shift_handovers WHERE id=COALESCE(NEW.handover_id,OLD.handover_id))<>'DRAFT' THEN
        RAISE EXCEPTION 'Submitted handover items are frozen' USING ERRCODE='23514'; END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$;
CREATE TRIGGER handover_item_edit BEFORE INSERT OR UPDATE OR DELETE ON handover_items
    FOR EACH ROW EXECUTE FUNCTION validate_handover_item_edit();

ALTER TABLE idempotency_requests ADD COLUMN result_handover_id BIGINT REFERENCES shift_handovers(id) ON DELETE RESTRICT;
ALTER TABLE idempotency_requests DROP CONSTRAINT idempotency_requests_operation_check;
ALTER TABLE idempotency_requests ADD CONSTRAINT idempotency_requests_operation_check CHECK (operation IN (
    'CHECK_IN','CHECK_OUT','HK_MANUAL_CREATE','HK_CLAIM','HK_ASSIGN','HK_REASSIGN','HK_START','HK_COMPLETE','HK_BATCH_ASSIGN',
    'ISSUE_REPORT','ISSUE_START','ISSUE_RESOLVE','ISSUE_SEVERITY','MAINTENANCE_STOP','MAINTENANCE_RESUME','ROOM_CHANGE','STAY_EXTEND','GUEST_CORRECT',
    'HANDOVER_CREATE','HANDOVER_SUBMIT','HANDOVER_ACKNOWLEDGE'
));
-- Wrap the previous CHECK to retain every existing result-kind restriction.
DO $$ DECLARE previous_check TEXT; BEGIN
    SELECT pg_get_constraintdef(oid) INTO previous_check FROM pg_constraint
        WHERE conrelid='idempotency_requests'::regclass AND conname='ck_request_result_kind';
    ALTER TABLE idempotency_requests DROP CONSTRAINT ck_request_result_kind;
    EXECUTE 'ALTER TABLE idempotency_requests ADD CONSTRAINT ck_request_result_kind CHECK ((operation NOT IN (''HANDOVER_CREATE'',''HANDOVER_SUBMIT'',''HANDOVER_ACKNOWLEDGE'') AND result_handover_id IS NULL AND '
        || substring(previous_check FROM 7) || ') OR (operation IN (''HANDOVER_CREATE'',''HANDOVER_SUBMIT'',''HANDOVER_ACKNOWLEDGE'') AND result_stay_id IS NULL AND result_task_log_id IS NULL AND result_assignment_batch_id IS NULL AND result_issue_log_id IS NULL AND result_maintenance_log_id IS NULL AND result_room_change_id IS NULL AND result_stay_extension_id IS NULL AND result_guest_correction_id IS NULL))';
END $$;
COMMENT ON TABLE shift_handovers IS 'Non-financial shift handovers. Submission freezes summary and items; acknowledgement is immutable. No cash, deposit or revenue fields.';
COMMENT ON TABLE handover_items IS 'Frozen handover snapshots referencing source categories/resource ids; never copy guest identity numbers or phone numbers here.';
COMMENT ON TABLE handover_events IS 'Append-only handover events: CREATED/UPDATED/SUBMITTED/REASSIGNED/ACKNOWLEDGED with reasons where applicable.';
