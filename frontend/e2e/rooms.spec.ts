import { test, expect, type Page, type APIRequestContext } from '@playwright/test'

const password = process.env.STAYOS_E2E_PASSWORD
if (!password) throw new Error('Run scripts/test.ps1 -Browser; test credentials must be generated at runtime')
const fixtures = JSON.parse(process.env.STAYOS_ROOM_FIXTURES || '{}') as Record<string, { id: number; roomNumber: string; roomTypeId: number; roomTypeName: string }>
async function login(page: Page, role: string) {
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill(`room_test_${role.toLowerCase()}`)
  await page.getByLabel('密码', { exact: true }).fill(password!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login/)
}
async function write(context: APIRequestContext, method: 'POST' | 'PUT', path: string, data: unknown) {
  const csrf = (await (await context.get('/api/auth/csrf')).json()).data as { headerName: string; token: string }
  return context.fetch(path, { method, data, headers: { [csrf.headerName]: csrf.token } })
}
for (const role of ['ADMIN', 'HOTEL_MANAGER', 'FRONT_DESK', 'HOUSEKEEPING_MANAGER', 'HOUSEKEEPING_STAFF']) {
  test(`${role}: 可查房态，基础配置入口按权限显示`, async ({ page }) => {
    await login(page, role)
    const nav = page.getByRole('navigation', { name: '房间功能' })
    await expect(nav.getByRole('link')).toHaveCount(role === 'ADMIN' ? 3 : 1)
    await nav.getByRole('link', { name: /房态图/ }).click()
    await expect(page.getByRole('heading', { name: '房态图', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: `查看房间 ${fixtures.clean!.roomNumber}`, exact: true })).toBeVisible()
    const body = (await (await page.request.get('/api/room-status?pageSize=24')).json()).data
    for (const [key, count] of Object.entries(body.statistics)) await expect(page.getByTestId(`stat-${key}`)).toHaveText(String(count))
    if (role !== 'ADMIN') {
      expect((await write(page.request, 'POST', '/api/rooms', { roomNumber: 'FORBIDDEN', floor: 1, roomTypeId: fixtures.clean!.roomTypeId })).status()).toBe(403)
      await page.goto('/manage/rooms')
      await expect(page.getByText('无权访问此工作区', { exact: true })).toBeVisible()
    }
  })
}

