test('旧页面修改被拒绝，不能覆盖另一个操作的新资料', async ({ page }) => {
  await login(page, 'ADMIN')
  await page.goto('/manage/rooms')
  const row = page.getByRole('row').filter({ hasText: fixtures.clean!.roomNumber })
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '编辑房间' })
  const room = (await (await page.request.get(`/api/rooms/${fixtures.clean!.id}`)).json()).data
  expect((await write(page.request, 'PUT', `/api/rooms/${room.id}`, { roomNumber: room.roomNumber, floor: room.floor, roomTypeId: room.roomTypeId, notes: '另一个操作的新备注', version: room.version })).status()).toBe(200)
  await dialog.getByLabel('备注', { exact: true }).fill('不应覆盖的新备注')
  await dialog.getByRole('button', { name: '保存房间', exact: true }).click()
  await expect(page.getByText('资料已被其他人修改，请刷新后重试', { exact: true })).toBeVisible()
  expect((await (await page.request.get(`/api/rooms/${room.id}`)).json()).data.notes).toBe('另一个操作的新备注')
})

